SUBROUTINE GET_MULT_DT_B(style, dtim, dv, dvb, geo, mpg, mpgb, ncv, nfc&
& , ns, te, teb, ti, na, ua, uab, te_min, te_max, mult_max, mult_maxb, &
& cmax, mult_dt, mult_dtb, dt_var4_ns, dt_var4_nsb, dt_var4_min, &
& dt_var4_minb, nfilter)
  USE B2MOD_TYPES
  USE B2MOD_CONSTANTS
  USE B2US_GEO_DIFF
  USE B2US_PLASMA_DIFF
  USE B2US_MAP_DIFF
  USE B2MOD_B2CMPA
  IMPLICIT NONE
!   ..input arguments
  TYPE(B2DERIVATIVES), INTENT(IN) :: dv
  TYPE(B2DERIVATIVES) :: dvb
  TYPE(GEOMETRY), INTENT(IN) :: geo
  TYPE(MAPPING), INTENT(IN) :: mpg
  TYPE(MAPPING_DIFF) :: mpgb
  INTEGER, INTENT(IN) :: style, ncv, nfc, ns, nfilter
  REAL(kind=r8), INTENT(IN) :: dtim, te_min, te_max, mult_max, te(ncv), &
& ti(ncv), na(ncv, 0:ns-1), ua(ncv, 0:ns-1), cmax
  REAL(kind=r8) :: mult_maxb, teb(ncv), uab(ncv, 0:ns-1)
!   ..output arguments
  REAL(kind=r8) :: mult_dt(ncv), dt_var4_ns(ncv, 0:ns-1), dt_var4_min(&
& ncv)
  REAL(kind=r8) :: mult_dtb(ncv), dt_var4_nsb(ncv, 0:ns-1), dt_var4_minb&
& (ncv)
!-----------------------------------------------------------------------
!.documentation
!
!     get_mult_dt calculates a local (cell-based) multiplier to the timestep. 
!     The style switch determines the model.
!
!     style = 0: no multiplier, dt_mult = 1.0
!
!     style = 1: based on Te. In low Te regions (typically more interaction with neutrals) a small timestep is preferred. 
!                In high Te regions there is typically less neutral interaction, or this interaction
!                is a least less critical from a numerical point of view. 
!
!     style = 2: based on the magnitude of the sources compared to the particle/momentum/energy content of the cell. 
!
!     style = 3: CFL-like criterium for drift velocities. Under development.
!
!     style = 4: Combination of option 2 and 3. The minimum of both options is taken. Under development. 
!
!     Other styles can be added in the future.
!
!-----------------------------------------------------------------------
!.declarations
!
!   ..local variables
  INTEGER :: icv, is, ifc, i1, i2, ifilter
  REAL(kind=r8) :: te_min_j, te_max_j, exp1, hx, hy, vx, vy, vx_a, vy_a&
& , vx_e, vy_e, dt3, dtx, dty, wrk0(ncv, 0:ns-1), wrk1(ncv, 0:ns-1), &
& uadia_c0(ncv, 0:ns-1), uadia_c1(ncv, 0:ns-1), vedia_c0(ncv), vedia_c1(&
& ncv), veecrb_c0(ncv), veecrb_c1(ncv), wrk00(0:ns-1), wrk11(0:ns-1), &
& dt4, mult_dt_tmp(ncv), min_mult
  REAL(kind=r8) :: exp1b, vxb, vyb, vx_ab, vy_ab, vx_eb, vy_eb, dt3b, &
& dtxb, dtyb, wrk0b(ncv, 0:ns-1), wrk1b(ncv, 0:ns-1), uadia_c0b(ncv, 0:&
& ns-1), uadia_c1b(ncv, 0:ns-1), vedia_c0b(ncv), vedia_c1b(ncv), &
& veecrb_c0b(ncv), veecrb_c1b(ncv), wrk00b(0:ns-1), wrk11b(0:ns-1), dt4b&
& , mult_dt_tmpb(ncv), min_multb
!   ..procedures
  EXTERNAL XERTST
  INTRINSIC LOG10
  INTRINSIC ABS
  INTRINSIC MAXVAL
  INTRINSIC MAX
  INTRINSIC MIN
  INTRINSIC MINVAL
  EXTERNAL XERRAB
  REAL(kind=r8) :: x1
  REAL(kind=r8) :: x1b
  REAL(kind=r8) :: x2
  REAL(kind=r8) :: x2b
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs0
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs0b
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs1
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs1b
  REAL(kind=r8) :: max1
  REAL(kind=r8) :: max1b
  REAL(kind=r8) :: max2
  REAL(kind=r8) :: max2b
  INTEGER :: arg1
  LOGICAL, DIMENSION(0:ns-1) :: mask
  LOGICAL, DIMENSION(0:ns-1) :: mask0
  INTEGER*4 :: branch
!-----------------------------------------------------------------------
!.computation  
!
!
  IF (style .NE. 0) THEN
    call xerrab('get_mult_dt_b to be checked and manually adjusted for adjoint AD!')
    IF (style .EQ. 1) THEN
!! convert from eV to joule
      te_min_j = te_min*ev
      te_max_j = te_max*ev
      DO icv=1,ncv
        IF (te(icv) .GE. te_max_j) THEN
          CALL PUSHCONTROL2B(2)
        ELSE IF (te(icv) .LE. te_min_j) THEN
          CALL PUSHCONTROL2B(1)
        ELSE
          CALL PUSHREAL8(exp1, r8/8)
          exp1 = LOG10(mult_max)*(LOG10(te(icv))-LOG10(te_min_j))/(LOG10&
&           (te_max_j)-LOG10(te_min_j))
          CALL PUSHCONTROL2B(0)
        END IF
      END DO
      DO icv=ncv,1,-1
        CALL POPCONTROL2B(branch)
        IF (branch .EQ. 0) THEN
          exp1b = 10**exp1*LOG(10.0)*mult_dtb(icv)
          mult_dtb(icv) = 0.D0
          CALL POPREAL8(exp1, r8/8)
          teb(icv) = teb(icv) + LOG10(mult_max)*exp1b/(te(icv)*LOG(10.0)&
&           *(LOG10(te_max_j)-LOG10(te_min_j)))
        ELSE IF (branch .EQ. 1) THEN
          mult_dtb(icv) = 0.D0
        ELSE
          mult_dtb(icv) = 0.D0
        END IF
      END DO
    ELSE IF (style .NE. 2) THEN
      IF (style .EQ. 3) THEN
!! interpolate drift velocities to cell centers
!c Highly experimental work! Use with care.
        arg1 = ns - 1
        CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellp, dv%uadia&
&                      (:, 0, :), uadia_c0)
        arg1 = ns - 1
        CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%uadia&
&                      (:, 1, :), uadia_c1)
        CALL INTCELL_FWD(nfc, ncv, mpg, mpg%intcellp, dv%vedia(:, 0), &
&                  vedia_c0)
        CALL INTCELL_FWD(nfc, ncv, mpg, mpg%intcellr, dv%vedia(:, 1), &
&                  vedia_c1)
        CALL INTCELL_FWD(nfc, ncv, mpg, mpg%intcellp, dv%veecrb(:, 0), &
&                  veecrb_c0)
        CALL INTCELL_FWD(nfc, ncv, mpg, mpg%intcellr, dv%veecrb(:, 1), &
&                  veecrb_c1)
        DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
          CALL PUSHREAL8(hy, r8/8)
          hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
          CALL PUSHREAL8(hx, r8/8)
          hx = geo%cvhz(icv)
          wrk00 = uadia_c0(icv, :) + geo%cvbb(icv, 0)/geo%cvbb(icv, 3)*&
&           ua(icv, :)
          wrk11 = uadia_c1(icv, :)
          mask = wrk00 .GE. 0.
          CALL PUSHREAL8ARRAY(dabs0, ns)
          WHERE (mask) dabs0 = wrk00
          CALL PUSHREAL8ARRAY(dabs0, ns)
          WHERE (.NOT.mask) dabs0 = -wrk00
          vx_a = MAXVAL(dabs0)
          x1 = vedia_c0(icv) + veecrb_c0(icv) + geo%cvbb(icv, 0)/geo%&
&           cvbb(icv, 3)*dv%ue(icv)
          IF (x1 .GE. 0.) THEN
            vx_e = x1
            CALL PUSHCONTROL1B(0)
          ELSE
            vx_e = -x1
            CALL PUSHCONTROL1B(1)
          END IF
          mask0 = wrk11 .GE. 0.
          CALL PUSHREAL8ARRAY(dabs1, ns)
          WHERE (mask0) dabs1 = wrk11
          CALL PUSHREAL8ARRAY(dabs1, ns)
          WHERE (.NOT.mask0) dabs1 = -wrk11
          vy_a = MAXVAL(dabs1)
          IF (vedia_c1(icv) + veecrb_c1(icv) .GE. 0.) THEN
            vy_e = vedia_c1(icv) + veecrb_c1(icv)
            CALL PUSHCONTROL1B(0)
          ELSE
            vy_e = -(vedia_c1(icv)+veecrb_c1(icv))
            CALL PUSHCONTROL1B(1)
          END IF
          IF (vx_a .LT. vx_e) THEN
            CALL PUSHREAL8(max1, r8/8)
            max1 = vx_e
            CALL PUSHCONTROL1B(0)
          ELSE
            CALL PUSHREAL8(max1, r8/8)
            max1 = vx_a
            CALL PUSHCONTROL1B(1)
          END IF
          dtx = cmax*hx/max1
          IF (vy_a .LT. vy_e) THEN
            CALL PUSHREAL8(max2, r8/8)
            max2 = vy_e
            CALL PUSHCONTROL1B(0)
          ELSE
            CALL PUSHREAL8(max2, r8/8)
            max2 = vy_a
            CALL PUSHCONTROL1B(1)
          END IF
          dty = cmax*hy/max2
          IF (dtx .GT. dty) THEN
            dt3 = dty
            CALL PUSHCONTROL1B(0)
          ELSE
            dt3 = dtx
            CALL PUSHCONTROL1B(1)
          END IF
          IF (dtim .LT. dt3) THEN
            x2 = dt3
            CALL PUSHCONTROL1B(0)
          ELSE
            x2 = dtim
            CALL PUSHCONTROL1B(1)
          END IF
          IF (x2 .GT. dtim*mult_max) THEN
            dt3 = dtim*mult_max
            CALL PUSHCONTROL1B(0)
          ELSE
            dt3 = x2
            CALL PUSHCONTROL1B(1)
          END IF
          mult_dt(icv) = dt3/dtim
        END DO
        DO ifilter=1,nfilter
          mult_dt_tmp = mult_dt
          DO ifc=1,nfc
            i1 = mpg%fccv(ifc, 1)
            i2 = mpg%fccv(ifc, 2)
            IF (mult_dt_tmp(i1) .GT. mult_dt_tmp(i2)) THEN
              min_mult = mult_dt_tmp(i2)
              CALL PUSHCONTROL1B(0)
            ELSE
              min_mult = mult_dt_tmp(i1)
              CALL PUSHCONTROL1B(1)
            END IF
            mult_dt(i1) = min_mult
            mult_dt(i2) = min_mult
          END DO
        END DO
        DO ifilter=nfilter,1,-1
          mult_dt_tmpb = 0.D0
          DO ifc=nfc,1,-1
            i2 = mpg%fccv(ifc, 2)
            min_multb = mult_dtb(i2)
            mult_dtb(i2) = 0.D0
            i1 = mpg%fccv(ifc, 1)
            min_multb = min_multb + mult_dtb(i1)
            mult_dtb(i1) = 0.D0
            CALL POPCONTROL1B(branch)
            IF (branch .EQ. 0) THEN
              mult_dt_tmpb(i2) = mult_dt_tmpb(i2) + min_multb
            ELSE
              mult_dt_tmpb(i1) = mult_dt_tmpb(i1) + min_multb
            END IF
          END DO
          mult_dtb = mult_dtb + mult_dt_tmpb
        END DO
        veecrb_c0b = 0.D0
        veecrb_c1b = 0.D0
        dabs0b = 0.D0
        dabs1b = 0.D0
        vedia_c0b = 0.D0
        vedia_c1b = 0.D0
        uadia_c0b = 0.D0
        uadia_c1b = 0.D0
        DO icv=ncv,1,-1
          dt3b = mult_dtb(icv)/dtim
          mult_dtb(icv) = 0.D0
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            x2b = 0.D0
          ELSE
            x2b = dt3b
          END IF
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            dt3b = x2b
          ELSE
            dt3b = 0.D0
          END IF
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            dtyb = dt3b
            dtxb = 0.D0
          ELSE
            dtxb = dt3b
            dtyb = 0.D0
          END IF
          max2b = -(cmax*hy*dtyb/max2**2)
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            CALL POPREAL8(max2, r8/8)
            vy_eb = max2b
            vy_ab = 0.D0
          ELSE
            CALL POPREAL8(max2, r8/8)
            vy_ab = max2b
            vy_eb = 0.D0
          END IF
          max1b = -(cmax*hx*dtxb/max1**2)
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            CALL POPREAL8(max1, r8/8)
            vx_eb = max1b
            vx_ab = 0.D0
          ELSE
            CALL POPREAL8(max1, r8/8)
            vx_ab = max1b
            vx_eb = 0.D0
          END IF
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            vedia_c1b(icv) = vedia_c1b(icv) + vy_eb
            veecrb_c1b(icv) = veecrb_c1b(icv) + vy_eb
          ELSE
            vedia_c1b(icv) = vedia_c1b(icv) - vy_eb
            veecrb_c1b(icv) = veecrb_c1b(icv) - vy_eb
          END IF
          !CALL MAXVAL_B(dabs1, dabs1b, vy_ab)
          wrk11 = uadia_c1(icv, :)
          mask0 = wrk11 .GE. 0.
          wrk11b = 0.D0
          CALL POPREAL8ARRAY(dabs1, ns)
          CALL POPREAL8ARRAY(dabs1, ns)
          WHERE (.NOT.mask0) 
            wrk11b = -dabs1b
            dabs1b = 0.D0
          ELSEWHERE
            wrk11b = wrk11b + dabs1b
            dabs1b = 0.D0
          END WHERE
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            x1b = vx_eb
          ELSE
            x1b = -vx_eb
          END IF
          vedia_c0b(icv) = vedia_c0b(icv) + x1b
          veecrb_c0b(icv) = veecrb_c0b(icv) + x1b
          dvb%ue(icv) = dvb%ue(icv) + geo%cvbb(icv, 0)*x1b/geo%cvbb(icv&
&           , 3)
          !CALL MAXVAL_B(dabs0, dabs0b, vx_ab)
          wrk00 = uadia_c0(icv, :) + geo%cvbb(icv, 0)/geo%cvbb(icv, 3)*&
&           ua(icv, :)
          mask = wrk00 .GE. 0.
          wrk00b = 0.D0
          CALL POPREAL8ARRAY(dabs0, ns)
          CALL POPREAL8ARRAY(dabs0, ns)
          uadia_c1b(icv, :) = uadia_c1b(icv, :) + wrk11b
          CALL POPREAL8(hx, r8/8)
          CALL POPREAL8(hy, r8/8)
          WHERE (.NOT.mask) 
            wrk00b = -dabs0b
            dabs0b = 0.D0
          ELSEWHERE
            wrk00b = wrk00b + dabs0b
            dabs0b = 0.D0
          END WHERE
          uadia_c0b(icv, :) = uadia_c0b(icv, :) + wrk00b
          uab(icv, :) = uab(icv, :) + geo%cvbb(icv, 0)*wrk00b/geo%cvbb(&
&           icv, 3)
        END DO
        CALL INTCELL_BWD(nfc, ncv, mpg, mpg%intcellr, dv%veecrb(:, 1), &
&                  dvb%veecrb(:, 1), veecrb_c1, veecrb_c1b)
        CALL INTCELL_BWD(nfc, ncv, mpg, mpg%intcellp, dv%veecrb(:, 0), &
&                  dvb%veecrb(:, 0), veecrb_c0, veecrb_c0b)
        CALL INTCELL_BWD(nfc, ncv, mpg, mpg%intcellr, dv%vedia(:, 1), &
&                  dvb%vedia(:, 1), vedia_c1, vedia_c1b)
        CALL INTCELL_BWD(nfc, ncv, mpg, mpg%intcellp, dv%vedia(:, 0), &
&                  dvb%vedia(:, 0), vedia_c0, vedia_c0b)
        CALL INTCELL1_B(nfc, ncv, arg1, mpg, mpgb, mpg%intcellr, dv%&
&                 uadia(:, 1, :), dvb%uadia(:, 1, :), uadia_c1, &
&                 uadia_c1b)
        arg1 = ns - 1
        CALL INTCELL1_B(nfc, ncv, arg1, mpg, mpgb, mpg%intcellp, dv%&
&                 uadia(:, 0, :), dvb%uadia(:, 0, :), uadia_c0, &
&                 uadia_c0b)
      ELSE IF (style .EQ. 4) THEN
!c Highly experimental work! Use with care.
!! For this option mult_dt is not used but other pre-compuations are performed here
!! interpolate drift velocities to cell centers
        arg1 = ns - 1
        CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellp, dv%uadia&
&                      (:, 0, :), wrk0)
        arg1 = ns - 1
        CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%uadia&
&                      (:, 1, :), wrk1)
        DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
          hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
          hx = geo%cvhz(icv)
          wrk00 = wrk0(icv, :)
          wrk11 = wrk1(icv, :)
          DO is=0,ns-1
            IF (wrk00(is) .GE. 0.) THEN
              CALL PUSHREAL8(vx, r8/8)
              vx = wrk00(is)
              CALL PUSHCONTROL1B(0)
            ELSE
              CALL PUSHREAL8(vx, r8/8)
              vx = -wrk00(is)
              CALL PUSHCONTROL1B(1)
            END IF
            IF (wrk11(is) .GE. 0.) THEN
              CALL PUSHREAL8(vy, r8/8)
              vy = wrk11(is)
              CALL PUSHCONTROL1B(0)
            ELSE
              CALL PUSHREAL8(vy, r8/8)
              vy = -wrk11(is)
              CALL PUSHCONTROL1B(1)
            END IF
            dtx = cmax*hx/(vx+0.001_R8)
            dty = cmax*hy/(vy+0.001_R8)
            IF (dtx .GT. dty) THEN
              dt4 = dty
              CALL PUSHCONTROL1B(0)
            ELSE
              dt4 = dtx
              CALL PUSHCONTROL1B(1)
            END IF
            CALL PUSHREAL8(dt_var4_ns(icv, is), r8/8)
            dt_var4_ns(icv, is) = dt4
          END DO
        END DO
        wrk0b = 0.D0
        wrk1b = 0.D0
        DO icv=ncv,1,-1
          !CALL MINVAL_B(dt_var4_ns(icv, :), dt_var4_nsb(icv, :), &
!&                 dt_var4_minb(icv))
          dt_var4_minb(icv) = 0.D0
          hx = geo%cvhz(icv)
          hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
          wrk00b = 0.D0
          wrk11b = 0.D0
          DO is=ns-1,0,-1
            CALL POPREAL8(dt_var4_ns(icv, is), r8/8)
            dt4b = dt_var4_nsb(icv, is)
            dt_var4_nsb(icv, is) = 0.D0
            CALL POPCONTROL1B(branch)
            IF (branch .EQ. 0) THEN
              dtyb = dt4b
              dtxb = 0.D0
            ELSE
              dtxb = dt4b
              dtyb = 0.D0
            END IF
            vyb = -(cmax*hy*dtyb/(vy+0.001_R8)**2)
            vxb = -(cmax*hx*dtxb/(vx+0.001_R8)**2)
            CALL POPCONTROL1B(branch)
            IF (branch .EQ. 0) THEN
              CALL POPREAL8(vy, r8/8)
              wrk11b(is) = wrk11b(is) + vyb
            ELSE
              CALL POPREAL8(vy, r8/8)
              wrk11b(is) = wrk11b(is) - vyb
            END IF
            CALL POPCONTROL1B(branch)
            IF (branch .EQ. 0) THEN
              CALL POPREAL8(vx, r8/8)
              wrk00b(is) = wrk00b(is) + vxb
            ELSE
              CALL POPREAL8(vx, r8/8)
              wrk00b(is) = wrk00b(is) - vxb
            END IF
          END DO
          wrk1b(icv, :) = wrk1b(icv, :) + wrk11b
          wrk0b(icv, :) = wrk0b(icv, :) + wrk00b
        END DO
        CALL INTCELL1_B(nfc, ncv, arg1, mpg, mpgb, mpg%intcellr, dv%&
&                 uadia(:, 1, :), dvb%uadia(:, 1, :), wrk1, wrk1b)
        arg1 = ns - 1
        CALL INTCELL1_B(nfc, ncv, arg1, mpg, mpgb, mpg%intcellp, dv%&
&                 uadia(:, 0, :), dvb%uadia(:, 0, :), wrk0, wrk0b)
      END IF
    END IF
  END IF
END SUBROUTINE GET_MULT_DT_B

