      arg1 = ncv*ns
      CALL CFWURE(iun, arg1, avg%sna_mean, 'sna_mean')
      CALL CFWURE(iun, ncv, avg%she_mean, 'she_mean')
      CALL CFWURE(iun, ncv, avg%shi_mean, 'shi_mean')
      CALL CFWURE(iun, ncv, avg%shn_mean, 'shn_mean')
