      CALL CFWUIN(iun, 2, idum, 'nCv,ns')
      CALL CFWUCH(iun, 120, lble, 'label')
      CALL B2WUZD(iun, newversion, ns, zamin, zamax, zn, am)
!
!   ..write average state and sources
      idum(0) = naver
      CALL CFWUIN(iun, 1, idum, 'naver')
      idum(0) = ntotdt
      CALL CFWUIN(iun, 1, idum, 'ntotdt')
