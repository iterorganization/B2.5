      CALL CFWURE(iun, arg1, sei_underrelax, 'sei_underrelax')
      arg1 = ncv*nstrata
      CALL CFWURE(iun, arg1, see_underrelax, 'see_underrelax')
    END IF
!
    CLOSE(iun) 
    WRITE(*, *) ' file ', savefile, ' written '
!
    CALL SUBEND()
    RETURN
