!-----------------------------------------------------------------------
!.computation
!
! ..preliminaries
!   ..subprogram start-up calls
  CALL SUBINI('b2srdt')
!   ..test nCv, ns
  CALL XERTST(0 .LT. ncv, 'faulty argument nCv')
  CALL XERTST(1 .LE. ns, 'faulty argument ns')
!   ..test sign of dtim
  CALL XERTST(0.0_R8 .LT. dtim, 'faulty argument dtim')
!   ..extensive tests on first few calls
  IF (ncall_b2srdt .LT. 3) THEN
!    ..test old state
    arg1 = ncv*ns
    CALL B2XVSG(arg1, na0, 1, 'na0', '.gt.')
    CALL B2XVSG(ncv, te0, 1, 'te0', '.gt.')
    CALL B2XVSG(ncv, ti0, 1, 'ti0', '.gt.')
    CALL B2XVSG(ncv, tn0, 1, 'tn0', '.gt.')
    CALL B2XVSG(ncv, ne0, 1, 'ne0', '.gt.')
    CALL B2XVSG(ncv, nn0, 1, 'nn0', '.ge.')
    arg1 = 2*ncv
    CALL B2XVSG(arg1, ni0, 1, 'ni0', '.gt.')
    arg1 = ncv*ns
    CALL B2XVSG(arg1, kinrgy0, 1, 'kinrgy0', '.ge.')
    CALL B2XVSG(ncv, kt0, 1, 'kt0', '.ge.')
    CALL B2XVSG(ncv, zt0, 1, 'zt0', '.ge.')
    mask = ua0 .GE. 0.
    WHERE (mask) 
      dabs0 = ua0
    ELSEWHERE
      dabs0 = -ua0
    END WHERE
    result1 = MAXVAL(dabs0)
    CALL XERTST(result1 .LT. c, 'Supra-luminal velocity !')
!    ..test current state
    arg1 = ncv*ns
    CALL B2XVSG(arg1, na, 1, 'na', '.gt.')
    CALL B2XVSG(ncv, te, 1, 'te', '.gt.')
    CALL B2XVSG(ncv, ti, 1, 'ti', '.gt.')
    CALL B2XVSG(ncv, tn, 1, 'tn', '.gt.')
    CALL B2XVSG(ncv, ne, 1, 'ne', '.gt.')
    CALL B2XVSG(ncv, nn, 1, 'nn', '.ge.')
    arg1 = 2*ncv
    CALL B2XVSG(arg1, ni, 1, 'ni', '.gt.')
    arg1 = ncv*ns
    CALL B2XVSG(arg1, kinrgy, 1, 'kinrgy', '.ge.')
    CALL B2XVSG(ncv, kt, 1, 'kt', '.ge.')
    CALL B2XVSG(ncv, zt, 1, 'zt', '.ge.')
    mask0 = ua .GE. 0.
    WHERE (mask0) 
      dabs1 = ua
    ELSEWHERE
      dabs1 = -ua
    END WHERE
    result1 = MAXVAL(dabs1)
    CALL XERTST(result1 .LT. c, 'Supra-luminal velocity !')
  END IF
!
! ..Optionally, calculate a local (cell-based) multiplier to the timestep.
!   mult_dt will be 1.0 if b2mndt_var_style = 0 (default).
  CALL GET_MULT_DT_NODIFF(switch%b2mndt_var_style, dtim, dv, geo, mpg, &
&                   ncv, mpg%nfc, ns, te, ti, na, ua, switch%&
&                   b2mndt_var_te_min, switch%b2mndt_var_te_max, switch%&
&                   b2mndt_var_mult, switch%b2mndt_var_style3_cmax, &
&                   mult_dt, dt_var4_ns, dt_var4_min, switch%&
&                   b2mndt_var_style_nfilter)
