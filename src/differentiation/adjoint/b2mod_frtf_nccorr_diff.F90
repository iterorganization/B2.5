            rtb%rz2(icv, is) = rtb%rz2(icv, is) + corr_fria(icv, is)*&
&             temp1*corr_fria_db(icv)
            tempb1 = corr_fria(icv, is)*rt%rz2(icv, is)*corr_fria_db(icv&
&             )/temp3
            plb%na(icv, is) = plb%na(icv, is) + tempb1
            z2n_cvb(icv, s2nucl(is)-1) = z2n_cvb(icv, s2nucl(is)-1) - &
&             temp1*tempb1
          END IF
          CALL POPCONTROL1B(branch)
          IF (branch .EQ. 0) THEN
            CALL POPREAL8(corr_tfia(icv, is), r8/8)
            tempb2 = corr_tfiab(icv, is)/k2_mean(icv)
            corr_tfiab(icv, is) = 0.D0
            temp_corrb(icv, 0, is) = temp_corrb(icv, 0, is) + temp_corr(&
&             icv, 1, is)*tempb2
            temp_corrb(icv, 1, is) = temp_corrb(icv, 1, is) + temp_corr(&
&             icv, 0, is)*tempb2
            temp_corrb(icv, 2, is) = temp_corrb(icv, 2, is) + tempb2
            k2_meanb(icv) = k2_meanb(icv) - (temp_corr(icv, 0, is)*&
&             temp_corr(icv, 1, is)+temp_corr(icv, 2, is))*tempb2/&
&             k2_mean(icv)
            CALL POPREAL8(temp_corr(icv, 2, is), r8/8)
            temp = SQRT(geo%fteps(ift)*geo%fteps(ift)*geo%fteps(ift))
            temp2 = temp*(g_hs_style(icv)*g_hs_style(icv)) + 1.0_R8
            tempb2 = geo%fteps(ift)**3*1.6_R8*temp_corrb(icv, 2, is)/&
&             temp2
            temp_corrb(icv, 2, is) = 0.D0
            g_hs_styleb(icv) = g_hs_styleb(icv) + (2*g_hs_style(icv)-2*&
&             g_hs_style(icv)**3*temp/temp2)*tempb2
            CALL POPREAL8(temp_corr(icv, 1, is), r8/8)
            temp0 = 0.4_R8*alpha_hs_style(icv, is) + 0.36_R8
            temp1 = temp0*(g_hs_style(icv)*g_hs_style(icv)) + 1.0_R8
            tempb1 = -(2.4_R8*SQRT(geo%fteps(ift)**3)*temp_corrb(icv, 1&
&             , is)/temp1**2)
            temp_corrb(icv, 1, is) = 0.D0
            CALL POPREAL8(temp_corr(icv, 0, is), r8/8)
            CALL POPREAL8(corr_fria(icv, is), r8/8)
            temp = g_hs_style(icv)*g_hs_style(icv) + 1.0_R8
            tempb0 = corr_friab(icv, is)/temp
            alpha_hs_styleb(icv, is) = alpha_hs_styleb(icv, is) + 0.4_R8&
&             *g_hs_style(icv)**2*tempb1 + (0.77_R8*alpha_hs_style(icv, &
&             is)**(-0.23)*0.44_R8-0.36_R8)*tempb0
            g_hs_styleb(icv) = g_hs_styleb(icv) + 2*g_hs_style(icv)*&
&             temp0*tempb1 - 2*g_hs_style(icv)*(0.44_R8*alpha_hs_style(&
&             icv, is)**0.77_R8-0.36_R8*alpha_hs_style(icv, is)+0.01_R8)&
&             *tempb0/temp
            temp0 = 2.5_R8*crtaancv(icv, s2nucl(pl%ismain)-1, s2nucl(is)&
&             -1)
            tempb = SQRT(2.0_R8)*temp_corrb(icv, 0, is)/temp0
            temp_corrb(icv, 0, is) = 0.D0
            chtaancvb(icv, s2nucl(pl%ismain)-1) = chtaancvb(icv, s2nucl(&
&             pl%ismain)-1) + tempb
            crtaancvb(icv, s2nucl(pl%ismain)-1, s2nucl(is)-1) = &
&             crtaancvb(icv, s2nucl(pl%ismain)-1, s2nucl(is)-1) - 2.5_R8&
&             *chtaancv(icv, s2nucl(pl%ismain)-1)*tempb/temp0
            corr_friab(icv, is) = 0.D0
          END IF
        END DO
      END IF
    END DO
    k2_tmpb = 0.D0
    DO icv=mpg%nci,1,-1
      CALL POPCONTROL2B(branch)
      IF (branch .NE. 0) THEN
        IF (branch .NE. 1) THEN
          ift = mpg%cvft(icv)
          tempb = k2_meanb(icv)/k2_tmp(ift, 1)
          k2_meanb(icv) = 0.D0
          k2_tmpb(ift, 0) = k2_tmpb(ift, 0) + tempb
          k2_tmpb(ift, 1) = k2_tmpb(ift, 1) - k2_tmp(ift, 0)*tempb/&
&           k2_tmp(ift, 1)
        END IF
      END IF
    END DO
    DO icv=mpg%nci,1,-1
      CALL POPCONTROL2B(branch)
      IF (branch .NE. 0) THEN
        IF (branch .NE. 1) THEN
          ift = mpg%cvft(icv)
          cob%k2(icv) = cob%k2(icv) + geo%cvvol(icv)*k2_tmpb(ift, 0)
        END IF
      END IF
    END DO
    CALL POPCONTROL1B(branch)
    IF (branch .EQ. 1) CALL POPREAL8ARRAY(corr_tfia, r8*SIZE(corr_tfia, &
&                                   1)*SIZE(corr_tfia, 2)/8)
    corr_tfiab = 0.D0
    CALL POPCONTROL1B(branch)
    IF (branch .EQ. 1) CALL POPREAL8ARRAY(corr_fria, r8*SIZE(corr_fria, &
&                                   1)*SIZE(corr_fria, 2)/8)
    corr_friab = 0.D0
    CALL POPCONTROL1B(branch)
    IF (branch .EQ. 1) CALL POPREAL8ARRAY(g_hs_style, r8*SIZE(g_hs_style&
&                                   , 1)/8)
    CALL POPCONTROL1B(branch)
    IF (branch .EQ. 1) CALL POPREAL8ARRAY(alpha_hs_style, r8*SIZE(&
&                                   alpha_hs_style, 1)*SIZE(&
&                                   alpha_hs_style, 2)/8)
    CALL B2MOD_FRTF_NCCORR_PREP_B(ncv, mpg, geo, pl, plb, co, cob, rt, &
&                           rtb, zeff, zeffb)
  END SUBROUTINE B2MOD_FRTF_NCCORR_COEFS_B

!
  SUBROUTINE B2MOD_FRTF_NCCORR_COEFS(ncv, nft, mpg, geo, pl, co, rt, &
&   switch, chtaancv, crtaancv, z2n_cv, zeff)
    USE B2US_MAP_DIFF
    USE B2US_GEO_DIFF
    USE B2US_PLASMA_DIFF
    USE B2MOD_SWITCHES_DIFF
    IMPLICIT NONE
    INTEGER, INTENT(IN) :: ncv, nft
    TYPE(MAPPING) :: mpg
    TYPE(GEOMETRY) :: geo
    TYPE(B2PLASMA) :: pl
    TYPE(B2COEFF) :: co
    TYPE(B2RATES) :: rt
    TYPE(SWITCHES) :: switch
    REAL(kind=r8) :: zeff(ncv), chtaancv(ncv, 0:nspecies-1), crtaancv(&
&   ncv, 0:nspecies-1, 0:nspecies-1), z2n_cv(ncv, 0:nspecies-1)
!-----------------------------------------------------------------------
!.documentation
!
!  1. purpose
!
!     B2MOD_FRTF_NCCORR_COEFS calculates correction coefficients.
!
!  3. description
!
!     This routine computes:
!     - corr_fria: a correction coefficient that is designed
!                  only for friction of chosen medium-to-high
!                  charged impurity with main ions
!     - corr_tfia: a correction coefficient that is designed
!                  only for thermal force of chosen medium-to-high
!                  charged impurity with main ions
!
!-----------------------------------------------------------------------
!  ..local variabless
    CHARACTER :: chns*3
    INTEGER, SAVE :: iout=0
    INTEGER :: corr_spec
    INTEGER :: icv, ift, is
    REAL(kind=r8) :: temp_corr(ncv, 0:2, 0:pl%ns-1), corr_fria_d(ncv), &
&   corr_tfia_d(ncv), k2_mean(ncv), k2_tmp(nft, 0:1)
    INTRINSIC SQRT
    CHARACTER(len=30) :: arg1
    CHARACTER(len=31) :: arg10
!-----------------------------------------------------------------------
!
    corr_spec = switch%zhdanov_nc_spec - 1
    CALL IPGETI('b2sifrtf_iout', iout)
    CALL B2MOD_FRTF_NCCORR_PREP(ncv, mpg, geo, pl, co, rt, zeff)
    corr_fria_d = 0.0_R8
    corr_tfia_d = 0.0_R8
    corr_fria = 1.0_R8
    corr_tfia = 1.0_R8
    temp_corr = 0.0_R8
    k2_mean = 0.0_R8
    k2_tmp = 0.0_R8
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) THEN
          k2_tmp(ift, 0) = k2_tmp(ift, 0) + co%k2(icv)*geo%cvvol(icv)
          k2_tmp(ift, 1) = k2_tmp(ift, 1) + geo%cvvol(icv)
        END IF
      END IF
    END DO
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) k2_mean(icv) = k2_tmp(ift, 0)/k2_tmp(ift, 1)
      END IF
    END DO
!
    DO icv=1,mpg%nci
! coefficients are calculated only inside the separatrix and for plasma with low main ion collisionality
      IF (mpg%cvonclosedsurface(icv) .AND. g_hs_style(icv) .LE. 5.0_R8) &
&     THEN
!this is a temporary decision
        ift = mpg%cvft(icv)
        DO is=0,pl%ns-1
!                if (switch%Zhdanov_closure.eq.1) then
!
          IF (rt%rza(icv, is) .GE. switch%zhdanov_nc_min .AND. ift .GT. &
&             0) THEN
! coefficients are calculated only for chosen ions of the chosen impurity
            corr_fria(icv, is) = 1.0_R8 + (-(0.36_R8*alpha_hs_style(icv&
&             , is))+0.44_R8*alpha_hs_style(icv, is)**0.77_R8+0.01_R8)/(&
&             1.0_R8+g_hs_style(icv)**2)
!
            temp_corr(icv, 0, is) = chtaancv(icv, s2nucl(pl%ismain)-1)*&
&             SQRT(2.0_R8)/(crtaancv(icv, s2nucl(pl%ismain)-1, s2nucl(is&
&             )-1)*2.5_R8)
            temp_corr(icv, 1, is) = 2.4_R8*SQRT(geo%fteps(ift)**3)/(&
&             1.0_R8+(0.36_R8+0.4_R8*alpha_hs_style(icv, is))*g_hs_style&
&             (icv)**2)
            temp_corr(icv, 2, is) = 1.6_R8*geo%fteps(ift)**3*g_hs_style(&
&             icv)**2/(1.0_R8+SQRT(geo%fteps(ift)**3)*g_hs_style(icv)**2&
&             )
            corr_tfia(icv, is) = (temp_corr(icv, 0, is)*temp_corr(icv, 1&
&             , is)+temp_corr(icv, 2, is))/k2_mean(icv)
          END IF
!
! the correction for main ions is calculated to make total forces zero
          IF (s2nucl(is) - 1 .EQ. corr_spec) THEN
!
            corr_fria_d(icv) = corr_fria_d(icv) + corr_fria(icv, is)*rt%&
&             rz2(icv, is)*pl%na(icv, is)/z2n_cv(icv, s2nucl(is)-1)
            corr_tfia_d(icv) = corr_tfia_d(icv) + corr_tfia(icv, is)*rt%&
&             rz2(icv, is)*pl%na(icv, is)/z2n_cv(icv, s2nucl(is)-1)
          END IF
        END DO
        corr_fria(icv, pl%ismain) = corr_fria_d(icv)
        corr_tfia(icv, pl%ismain) = corr_tfia_d(icv)
!
      END IF
    END DO
!
    IF (iout .NE. 0) THEN
!  .or. iout_b2wdat.eq.4) then
      DO is=0,pl%ns-1
        WRITE(chns, '(i3.3)') is
        arg1 = 'b2mod_frtf_nccorr_coefs_temp0_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 0, is), arg1)
        arg1 = 'b2mod_frtf_nccorr_coefs_temp1_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 1, is), arg1)
        arg1 = 'b2mod_frtf_nccorr_coefs_temp2_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 2, is), arg1)
      END DO
      arg10 = 'b2mod_frtf_nccorr_coefs_k2mean_'//chns
      CALL MY_OUT_US(70, ncv, 0, k2_mean, arg10)
    END IF
!
    RETURN
  END SUBROUTINE B2MOD_FRTF_NCCORR_COEFS
!

END MODULE B2MOD_FRTF_NCCORR_DIFF

