!.specification
!
SUBROUTINE GET_MULT_DT_NODIFF_NODIFF(style, dtim, dv, geo, mpg, ncv, nfc&
& , ns, te, ti, na, ua, te_min, te_max, mult_max, cmax, mult_dt, &
& dt_var4_ns, dt_var4_min, nfilter)
  USE B2MOD_TYPES
  USE B2MOD_CONSTANTS
  USE B2US_GEO_DIFFV_DIFFV
  USE B2US_PLASMA_DIFFV_DIFFV
  USE B2US_MAP_DIFFV_DIFFV
  USE B2MOD_B2CMPA_DIFFV
  USE B2MOD_DIFFSIZES
  IMPLICIT NONE
!   ..input arguments
  TYPE(B2DERIVATIVES), INTENT(IN) :: dv
  TYPE(GEOMETRY), INTENT(IN) :: geo
  TYPE(MAPPING), INTENT(IN) :: mpg
  INTEGER, INTENT(IN) :: style, ncv, nfc, ns, nfilter
  REAL(kind=r8), INTENT(IN) :: dtim, te_min, te_max, mult_max, te(ncv), &
& ti(ncv), na(ncv, 0:ns-1), ua(ncv, 0:ns-1), cmax
!   ..output arguments
  REAL(kind=r8), INTENT(OUT) :: mult_dt(ncv), dt_var4_ns(ncv, 0:ns-1), &
& dt_var4_min(ncv)
!-----------------------------------------------------------------------
!.documentation
!
!     get_mult_dt calculates a local (cell-based) multiplier to the timestep. 
!     The style switch determines the model.
!
!     style = 0: no multiplier, dt_mult = 1.0
!
!     style = 1: based on Te. In low Te regions (typically more interaction with neutrals) a small timestep is preferred. 
!                In high Te regions there is typically less neutral interaction, or this interaction
!                is a least less critical from a numerical point of view. 
!
!     style = 2: based on the magnitude of the sources compared to the particle/momentum/energy content of the cell. 
!
!     style = 3: CFL-like criterium for drift velocities. Under development.
!
!     style = 4: Combination of option 2 and 3. The minimum of both options is taken. Under development. 
!
!     Other styles can be added in the future.
!
!-----------------------------------------------------------------------
!.declarations
!
!   ..local variables
  INTEGER :: icv, is, ifc, i1, i2, ifilter
  REAL(kind=r8) :: te_min_j, te_max_j, exp1, hx, hy, vx, vy, vx_a, vy_a&
& , vx_e, vy_e, dt3, dtx, dty, wrk0(ncv, 0:ns-1), wrk1(ncv, 0:ns-1), &
& uadia_c0(ncv, 0:ns-1), uadia_c1(ncv, 0:ns-1), vedia_c0(ncv), vedia_c1(&
& ncv), veecrb_c0(ncv), veecrb_c1(ncv), wrk00(0:ns-1), wrk11(0:ns-1), &
& dt4, mult_dt_tmp(ncv), min_mult
!   ..procedures
  EXTERNAL XERTST
  INTRINSIC LOG10
  INTRINSIC ABS
  INTRINSIC MAXVAL
  INTRINSIC MAX
  INTRINSIC MIN
  INTRINSIC MINVAL
  EXTERNAL XERRAB
  REAL(kind=r8) :: x1
  REAL(kind=r8) :: x2
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs0
  DOUBLE PRECISION, DIMENSION(0:ns-1) :: dabs1
  REAL(kind=r8) :: max1
  REAL(kind=r8) :: max2
  INTEGER :: arg1
!-----------------------------------------------------------------------
!.computation  
!
!
  IF (style .EQ. 0) THEN
    mult_dt = 1.0_R8
  ELSE IF (style .EQ. 1) THEN
!! convert from eV to joule
    te_min_j = te_min*ev
    te_max_j = te_max*ev
    DO icv=1,ncv
      IF (te(icv) .GE. te_max_j) THEN
        mult_dt(icv) = mult_max
      ELSE IF (te(icv) .LE. te_min_j) THEN
        mult_dt(icv) = 1.0_R8
      ELSE
        exp1 = LOG10(mult_max)*(LOG10(te(icv))-LOG10(te_min_j))/(LOG10(&
&         te_max_j)-LOG10(te_min_j))
        mult_dt(icv) = 10**exp1
      END IF
    END DO
  ELSE IF (style .EQ. 2) THEN
!! This option is worked out in b2srdt itself.
    mult_dt = 1.0_R8
  ELSE IF (style .EQ. 3) THEN
!! interpolate drift velocities to cell centers
!c Highly experimental work! Use with care.
    arg1 = ns - 1
    CALL INTCELL1_NODIFF_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellp, dv%&
&                         uadia(:, 0, :), uadia_c0)
    arg1 = ns - 1
    CALL INTCELL1_NODIFF_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%&
&                         uadia(:, 1, :), uadia_c1)
    CALL INTCELL_NODIFF_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%vedia(:, &
&                        0), vedia_c0)
    CALL INTCELL_NODIFF_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%vedia(:, &
&                        1), vedia_c1)
    CALL INTCELL_NODIFF_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%veecrb(:&
&                        , 0), veecrb_c0)
    CALL INTCELL_NODIFF_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%veecrb(:&
&                        , 1), veecrb_c1)
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      wrk00 = uadia_c0(icv, :) + geo%cvbb(icv, 0)/geo%cvbb(icv, 3)*ua(&
&       icv, :)
      wrk11 = uadia_c1(icv, :)
      WHERE (wrk00 .GE. 0.) 
        dabs0 = wrk00
      ELSEWHERE
        dabs0 = -wrk00
      END WHERE
      vx_a = MAXVAL(dabs0)
      x1 = vedia_c0(icv) + veecrb_c0(icv) + geo%cvbb(icv, 0)/geo%cvbb(&
&       icv, 3)*dv%ue(icv)
      IF (x1 .GE. 0.) THEN
        vx_e = x1
      ELSE
        vx_e = -x1
      END IF
      WHERE (wrk11 .GE. 0.) 
        dabs1 = wrk11
      ELSEWHERE
        dabs1 = -wrk11
      END WHERE
      vy_a = MAXVAL(dabs1)
      IF (vedia_c1(icv) + veecrb_c1(icv) .GE. 0.) THEN
        vy_e = vedia_c1(icv) + veecrb_c1(icv)
      ELSE
        vy_e = -(vedia_c1(icv)+veecrb_c1(icv))
      END IF
      IF (vx_a .LT. vx_e) THEN
        max1 = vx_e
      ELSE
        max1 = vx_a
      END IF
      dtx = cmax*hx/max1
      IF (vy_a .LT. vy_e) THEN
        max2 = vy_e
      ELSE
        max2 = vy_a
      END IF
      dty = cmax*hy/max2
      IF (dtx .GT. dty) THEN
        dt3 = dty
      ELSE
        dt3 = dtx
      END IF
      IF (dtim .LT. dt3) THEN
        x2 = dt3
      ELSE
        x2 = dtim
      END IF
      IF (x2 .GT. dtim*mult_max) THEN
        dt3 = dtim*mult_max
      ELSE
        dt3 = x2
      END IF
      mult_dt(icv) = dt3/dtim
    END DO
    DO ifilter=1,nfilter
      mult_dt_tmp = mult_dt
      DO ifc=1,nfc
        i1 = mpg%fccv(ifc, 1)
        i2 = mpg%fccv(ifc, 2)
        IF (mult_dt_tmp(i1) .GT. mult_dt_tmp(i2)) THEN
          min_mult = mult_dt_tmp(i2)
        ELSE
          min_mult = mult_dt_tmp(i1)
        END IF
        mult_dt(i1) = min_mult
        mult_dt(i2) = min_mult
      END DO
    END DO
  ELSE IF (style .EQ. 4) THEN
!c Highly experimental work! Use with care.
!! For this option mult_dt is not used but other pre-compuations are performed here
!! interpolate drift velocities to cell centers
    mult_dt = 1.0_R8
    arg1 = ns - 1
    CALL INTCELL1_NODIFF_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellp, dv%&
&                         uadia(:, 0, :), wrk0)
    arg1 = ns - 1
    CALL INTCELL1_NODIFF_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%&
&                         uadia(:, 1, :), wrk1)
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      wrk00 = wrk0(icv, :)
      wrk11 = wrk1(icv, :)
      DO is=0,ns-1
        IF (wrk00(is) .GE. 0.) THEN
          vx = wrk00(is)
        ELSE
          vx = -wrk00(is)
        END IF
        IF (wrk11(is) .GE. 0.) THEN
          vy = wrk11(is)
        ELSE
          vy = -wrk11(is)
        END IF
        dtx = cmax*hx/(vx+0.001_R8)
        dty = cmax*hy/(vy+0.001_R8)
        IF (dtx .GT. dty) THEN
          dt4 = dty
        ELSE
          dt4 = dtx
        END IF
        dt_var4_ns(icv, is) = dt4
      END DO
      dt_var4_min(icv) = MINVAL(dt_var4_ns(icv, :))
    END DO
  ELSE
!
    CALL XERRAB('This b2mndt_var_style is not available')
  END IF
!
!   ..return
  RETURN
!
!-----------------------------------------------------------------------
!
!
END SUBROUTINE GET_MULT_DT_NODIFF_NODIFF

