    arg1 = ns - 1
    uadia_c1d = 0.d0
    CALL INTCELL1_DV_NODIFF(nfc, ncv, arg1, mpg, mpgd, mpg%intcellr, dv%&
&                     uadia(:, 1, :), dvd%uadia(:, :, 1, :), uadia_c1, &
&                     uadia_c1d, nbdirs)
    vedia_c0d = 0.d0
    CALL INTCELL_DV_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%vedia(:, 0), &
&                    dvd%vedia(:, :, 0), vedia_c0, vedia_c0d, nbdirs)
    vedia_c1d = 0.d0
    CALL INTCELL_DV_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%vedia(:, 1), &
&                    dvd%vedia(:, :, 1), vedia_c1, vedia_c1d, nbdirs)
    veecrb_c0d = 0.d0
    CALL INTCELL_DV_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%veecrb(:, 0)&
&                    , dvd%veecrb(:, :, 0), veecrb_c0, veecrb_c0d, &
&                    nbdirs)
    veecrb_c1d = 0.d0
    CALL INTCELL_DV_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%veecrb(:, 1)&
&                    , dvd%veecrb(:, :, 1), veecrb_c1, veecrb_c1d, &
&                    nbdirs)
    mult_dtd = 0.d0
    dabs0d = 0.d0
    dabs1d = 0.d0
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      DO nd=1,nbdirs
        wrk00d(nd, :) = uadia_c0d(nd, icv, :) + geo%cvbb(icv, 0)*uad(nd&
&         , icv, :)/geo%cvbb(icv, 3)
        wrk11d(nd, :) = uadia_c1d(nd, icv, :)
        x1d(nd) = vedia_c0d(nd, icv) + veecrb_c0d(nd, icv) + geo%cvbb(&
&         icv, 0)*dvd%ue(nd, icv)/geo%cvbb(icv, 3)
      END DO
      wrk00 = uadia_c0(icv, :) + geo%cvbb(icv, 0)/geo%cvbb(icv, 3)*ua(&
&       icv, :)
      wrk11 = uadia_c1(icv, :)
      DO nd=1,nbdirs
        WHERE (wrk00 .GE. 0.) dabs0d(nd, :) = wrk00d(nd, :)
      END DO
      WHERE (wrk00 .GE. 0.) dabs0 = wrk00
      DO nd=1,nbdirs
        WHERE (.NOT.wrk00 .GE. 0.) dabs0d(nd, :) = -wrk00d(nd, :)
      END DO
      WHERE (.NOT.wrk00 .GE. 0.) dabs0 = -wrk00
      x1 = vedia_c0(icv) + veecrb_c0(icv) + geo%cvbb(icv, 0)/geo%cvbb(&
&       icv, 3)*dv%ue(icv)
      IF (x1 .GE. 0.) THEN
        DO nd=1,nbdirs
          vx_ed(nd) = x1d(nd)
        END DO
        vx_e = x1
      ELSE
        DO nd=1,nbdirs
          vx_ed(nd) = -x1d(nd)
        END DO
        vx_e = -x1
      END IF
      DO nd=1,nbdirs
        WHERE (wrk11 .GE. 0.) dabs1d(nd, :) = wrk11d(nd, :)
      END DO
      WHERE (wrk11 .GE. 0.) dabs1 = wrk11
      DO nd=1,nbdirs
        WHERE (.NOT.wrk11 .GE. 0.) dabs1d(nd, :) = -wrk11d(nd, :)
      END DO
      WHERE (.NOT.wrk11 .GE. 0.) dabs1 = -wrk11
      IF (vedia_c1(icv) + veecrb_c1(icv) .GE. 0.) THEN
        DO nd=1,nbdirs
          vy_ed(nd) = vedia_c1d(nd, icv) + veecrb_c1d(nd, icv)
        END DO
        vy_e = vedia_c1(icv) + veecrb_c1(icv)
      ELSE
        DO nd=1,nbdirs
          vy_ed(nd) = -vedia_c1d(nd, icv) - veecrb_c1d(nd, icv)
        END DO
        vy_e = -(vedia_c1(icv)+veecrb_c1(icv))
      END IF
      IF (vx_a .LT. vx_e) THEN
        DO nd=1,nbdirs
          max1d(nd) = vx_ed(nd)
        END DO
        max1 = vx_e
      ELSE
        DO nd=1,nbdirs
          max1d(nd) = vx_ad(nd)
        END DO
        max1 = vx_a
      END IF
      temp0 = cmax*hx/max1
      DO nd=1,nbdirs
        dtxd(nd) = -(temp0*max1d(nd)/max1)
      END DO
      dtx = temp0
      IF (vy_a .LT. vy_e) THEN
        DO nd=1,nbdirs
          max2d(nd) = vy_ed(nd)
        END DO
        max2 = vy_e
      ELSE
        DO nd=1,nbdirs
          max2d(nd) = vy_ad(nd)
        END DO
        max2 = vy_a
      END IF
      temp0 = cmax*hy/max2
      DO nd=1,nbdirs
        dtyd(nd) = -(temp0*max2d(nd)/max2)
      END DO
      dty = temp0
      IF (dtx .GT. dty) THEN
        DO nd=1,nbdirs
          dt3d(nd) = dtyd(nd)
        END DO
        dt3 = dty
      ELSE
        DO nd=1,nbdirs
          dt3d(nd) = dtxd(nd)
        END DO
        dt3 = dtx
      END IF
      IF (dtim .LT. dt3) THEN
        DO nd=1,nbdirs
          x2d(nd) = dt3d(nd)
        END DO
        x2 = dt3
      ELSE
        x2 = dtim
        x2d = 0.d0
      END IF
      IF (x2 .GT. dtim*mult_max) THEN
        dt3 = dtim*mult_max
        dt3d = 0.d0
      ELSE
        DO nd=1,nbdirs
          dt3d(nd) = x2d(nd)
        END DO
        dt3 = x2
      END IF
      DO nd=1,nbdirs
        mult_dtd(nd, icv) = dt3d(nd)/dtim
      END DO
      mult_dt(icv) = dt3/dtim
    END DO
    DO ifilter=1,nfilter
      DO nd=1,nbdirs
        mult_dt_tmpd(nd, :) = mult_dtd(nd, :)
      END DO
      mult_dt_tmp = mult_dt
      DO ifc=1,nfc
        i1 = mpg%fccv(ifc, 1)
        i2 = mpg%fccv(ifc, 2)
        IF (mult_dt_tmp(i1) .GT. mult_dt_tmp(i2)) THEN
          DO nd=1,nbdirs
            min_multd(nd) = mult_dt_tmpd(nd, i2)
          END DO
          min_mult = mult_dt_tmp(i2)
        ELSE
          DO nd=1,nbdirs
            min_multd(nd) = mult_dt_tmpd(nd, i1)
          END DO
          min_mult = mult_dt_tmp(i1)
        END IF
        DO nd=1,nbdirs
          mult_dtd(nd, i1) = min_multd(nd)
          mult_dtd(nd, i2) = min_multd(nd)
        END DO
        mult_dt(i1) = min_mult
        mult_dt(i2) = min_mult
      END DO
    END DO
    dt_var4_nsd = 0.d0
    dt_var4_mind = 0.d0
  ELSE IF (style .EQ. 4) THEN
!c Highly experimental work! Use with care.
!! For this option mult_dt is not used but other pre-compuations are performed here
!! interpolate drift velocities to cell centers
    mult_dt = 1.0_R8
    arg1 = ns - 1
    wrk0d = 0.d0
    CALL INTCELL1_DV_NODIFF(nfc, ncv, arg1, mpg, mpgd, mpg%intcellp, dv%&
&                     uadia(:, 0, :), dvd%uadia(:, :, 0, :), wrk0, wrk0d&
&                     , nbdirs)
    arg1 = ns - 1
    wrk1d = 0.d0
    CALL INTCELL1_DV_NODIFF(nfc, ncv, arg1, mpg, mpgd, mpg%intcellr, dv%&
&                     uadia(:, 1, :), dvd%uadia(:, :, 1, :), wrk1, wrk1d&
&                     , nbdirs)
    dt_var4_nsd = 0.d0
    dt_var4_mind = 0.d0
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      DO nd=1,nbdirs
        wrk00d(nd, :) = wrk0d(nd, icv, :)
        wrk11d(nd, :) = wrk1d(nd, icv, :)
      END DO
      wrk00 = wrk0(icv, :)
      wrk11 = wrk1(icv, :)
      DO is=0,ns-1
        IF (wrk00(is) .GE. 0.) THEN
          DO nd=1,nbdirs
            vxd(nd) = wrk00d(nd, is)
          END DO
          vx = wrk00(is)
        ELSE
          DO nd=1,nbdirs
            vxd(nd) = -wrk00d(nd, is)
          END DO
          vx = -wrk00(is)
        END IF
        IF (wrk11(is) .GE. 0.) THEN
          DO nd=1,nbdirs
            vyd(nd) = wrk11d(nd, is)
          END DO
          vy = wrk11(is)
        ELSE
          DO nd=1,nbdirs
            vyd(nd) = -wrk11d(nd, is)
          END DO
          vy = -wrk11(is)
        END IF
        temp0 = cmax*hx/(vx+0.001_R8)
        DO nd=1,nbdirs
          dtxd(nd) = -(temp0*vxd(nd)/(vx+0.001_R8))
        END DO
        dtx = temp0
        temp0 = cmax*hy/(vy+0.001_R8)
        DO nd=1,nbdirs
          dtyd(nd) = -(temp0*vyd(nd)/(vy+0.001_R8))
        END DO
        dty = temp0
        IF (dtx .GT. dty) THEN
          DO nd=1,nbdirs
            dt4d(nd) = dtyd(nd)
          END DO
          dt4 = dty
        ELSE
          DO nd=1,nbdirs
            dt4d(nd) = dtxd(nd)
          END DO
          dt4 = dtx
        END IF
        DO nd=1,nbdirs
          dt_var4_nsd(nd, icv, is) = dt4d(nd)
        END DO
        dt_var4_ns(icv, is) = dt4
      END DO
! csc manually adjusted part, not sure if this will be correct
      idx = MINLOC(dt_var4_ns(icv, :))
      DO nd=1,nbdirs
        dt_var4_mind(nd, icv) = dt_var4_nsd(nd, icv, idx(1))
      END DO
      dt_var4_min(icv) = dt_var4_ns(icv, idx(1))
    END DO
    mult_dtd = 0.d0
  ELSE
!
    CALL XERRAB('This b2mndt_var_style is not available')
    dt_var4_nsd = 0.d0
    dt_var4_mind = 0.d0
    mult_dtd = 0.d0
  END IF
!
!   ..return
  RETURN
!
!-----------------------------------------------------------------------
!
!
END SUBROUTINE GET_MULT_DT_DV_NODIFF

!
!
!
