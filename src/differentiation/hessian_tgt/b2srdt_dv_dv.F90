    t0 = switch%b2srdt_phm4/dtim*geo%cvvol(icv)*qe*time_factor(icv)
!xpb
    sr%schdt(icv, 0) = t0*(ni0(icv, 0)-ne0(icv))
    sr%schdt(icv, 1) = 0.0_R8
    sr%schdt(icv, 2) = 0.0_R8
!xpb
    sr%schdt(icv, 3) = -t0
    IF (.NOT.lout) sr%sch(icv, :) = sr%sch(icv, :) + sr%schdt(icv, :)
  END DO
