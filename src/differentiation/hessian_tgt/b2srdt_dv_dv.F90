      END DO
      DO k=0,1
        WRITE(chk, '(i1)') k
        arg10 = 'b2srdt_snadt'//chk//chns
        CALL MY_OUT_US(70, ncv, 0, sr%snadt(1, k, is), arg10)
      END DO
