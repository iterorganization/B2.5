  DO icv=1,mpg%nci
!WG_TODO          if(iftimbound(iCv) .ne. 0) cycle
!xpb
    t0 = switch%b2srdt_phm5/dtim*geo%cvvol(icv)*time_factor(icv)
    sr%snedt(icv, 0) = t0*ne0(icv)
    sr%snedt(icv, 1) = -t0
