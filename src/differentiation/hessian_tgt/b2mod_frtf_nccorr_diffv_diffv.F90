    TYPE(B2RATES) :: rt
    TYPE(B2RATES_DIFFV) :: rtd
    REAL(kind=r8) :: zeff(ncv)
    REAL(kind=r8) :: zeffd(nbdirsmax, ncv)
!   ..local variables
    INTEGER :: icv, is
    INTRINSIC SQRT
    REAL(kind=r8) :: arg1
    REAL(kind=r8) :: result1
    INTEGER :: nd
    REAL(r8) :: temp
    INTEGER :: nbdirs
!
!-----------------------------------------------------------------------
!.documentation
!
!  1. purpose
!
!     B2MOD_FRTF_NCCORR_PREP stores a parameter of relative impurity presence
!     and main ion collisionality (neoclassical style, see the manual).
!
!  3. description
!
!     This module contains:
!     - alpha_HS_style: ratio of the squared charge weighted density of
!                       impurity ions to the main ion density
!     - g_HS_style    : collisionality of main ions multiplied by \eps^{3/2}
!                       and divided by a component containing impurity presence
!
!-----------------------------------------------------------------------
!
    DO icv=1,mpg%nci
      DO is=0,pl%ns-1
        temp = pl%na(icv, is)*rt%rz2(icv, is)/pl%na(icv, pl%ismain)
        DO nd=1,nbdirs
          alpha_hs_styled(nd, icv, is) = (rt%rz2(icv, is)*pld%na(nd, icv&
&           , is)+pl%na(icv, is)*rtd%rz2(nd, icv, is)-temp*pld%na(nd, &
&           icv, pl%ismain))/pl%na(icv, pl%ismain)
        END DO
        alpha_hs_style(icv, is) = temp
      END DO
      IF (mpg%cvft(icv) .GT. 0) THEN
        arg1 = geo%fteps(mpg%cvft(icv))**3
        result1 = SQRT(arg1)
        temp = co%nu2(icv)/zeff(icv)
        DO nd=1,nbdirs
          g_hs_styled(nd, icv) = result1*(cod%nu2(nd, icv)-temp*zeffd(nd&
&           , icv))/zeff(icv)
        END DO
        g_hs_style(icv) = result1*temp
      END IF
    END DO
!
    RETURN
  END SUBROUTINE B2MOD_FRTF_NCCORR_PREP_DV

