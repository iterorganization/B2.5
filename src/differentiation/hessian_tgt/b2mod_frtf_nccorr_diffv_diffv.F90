    USE B2US_GEO_DIFFV_DIFFV
    USE B2US_PLASMA_DIFFV_DIFFV
    USE B2MOD_SWITCHES_DIFFV_DIFFV
!  Hint: nbdirsmax should be the maximum number of differentiation directions
    USE B2MOD_DIFFSIZES
!  Hint: nbdirsmax0 should be the maximum number of differentiation directions
    IMPLICIT NONE
    INTEGER, INTENT(IN) :: ncv, nft
    TYPE(MAPPING) :: mpg
    TYPE(MAPPING_DIFFV) :: mpgd
    TYPE(GEOMETRY) :: geo
    TYPE(GEOMETRY_DIFFV0) :: geod0
    TYPE(GEOMETRY_DIFFV) :: geod
    TYPE(B2PLASMA) :: pl
    TYPE(B2PLASMA_DIFFV0) :: pld0
    TYPE(B2PLASMA_DIFFV) :: pld
    TYPE(B2PLASMA_DIFFV_DIFFV) :: pldd
    TYPE(B2COEFF) :: co
    TYPE(B2COEFF_DIFFV0) :: cod0
    TYPE(B2COEFF_DIFFV) :: cod
    TYPE(B2COEFF_DIFFV_DIFFV) :: codd
    TYPE(B2RATES) :: rt
    TYPE(B2RATES_DIFFV0) :: rtd0
    TYPE(B2RATES_DIFFV) :: rtd
    TYPE(B2RATES_DIFFV_DIFFV) :: rtdd
    TYPE(SWITCHES) :: switch
    REAL(kind=r8) :: zeff(ncv), chtaancv(ncv, 0:nspecies-1), crtaancv(&
&   ncv, 0:nspecies-1, 0:nspecies-1), z2n_cv(ncv, 0:nspecies-1)
    REAL(kind=r8) :: zeffd0(nbdirsmax0, ncv), chtaancvd0(nbdirsmax0, ncv&
