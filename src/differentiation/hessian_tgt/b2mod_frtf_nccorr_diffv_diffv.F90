  SUBROUTINE B2MOD_FRTF_NCCORR_PREP(ncv, mpg, geo, pl, co, rt, zeff)
    USE B2US_GEO_DIFFV_DIFFV
    USE B2US_MAP_DIFFV_DIFFV
    USE B2US_PLASMA_DIFFV_DIFFV
    USE B2MOD_DIFFSIZES
    IMPLICIT NONE
!
    INTEGER :: ncv
    TYPE(MAPPING) :: mpg
    TYPE(GEOMETRY) :: geo
    TYPE(B2PLASMA) :: pl
    TYPE(B2COEFF) :: co
    TYPE(B2RATES) :: rt
    REAL(kind=r8) :: zeff(ncv)
!   ..local variables
    INTEGER :: icv, is
    INTRINSIC SQRT
    REAL(kind=r8) :: arg1
    REAL(kind=r8) :: result1
!
!-----------------------------------------------------------------------
!.documentation
!
!  1. purpose
!
!     B2MOD_FRTF_NCCORR_PREP stores a parameter of relative impurity presence
!     and main ion collisionality (neoclassical style, see the manual).
!
!  3. description
!
!     This module contains:
!     - alpha_HS_style: ratio of the squared charge weighted density of
!                       impurity ions to the main ion density
!     - g_HS_style    : collisionality of main ions multiplied by \eps^{3/2}
!                       and divided by a component containing impurity presence
!
