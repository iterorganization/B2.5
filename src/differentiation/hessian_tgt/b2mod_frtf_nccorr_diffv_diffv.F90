&   nbdirsmax, ncv, 0:nspecies-1, 0:nspecies-1), z2n_cvdd(nbdirsmax0, &
&   nbdirsmax, ncv, 0:nspecies-1)
!-----------------------------------------------------------------------
!.documentation
!
!  1. purpose
!
!     B2MOD_FRTF_NCCORR_COEFS calculates correction coefficients.
!
!  3. description
!
!     This routine computes:
!     - corr_fria: a correction coefficient that is designed
!                  only for friction of chosen medium-to-high
!                  charged impurity with main ions
!     - corr_tfia: a correction coefficient that is designed
!                  only for thermal force of chosen medium-to-high
!                  charged impurity with main ions
!
!-----------------------------------------------------------------------
!  ..local variabless
    CHARACTER :: chns*3
    INTEGER, SAVE :: iout=0
    INTEGER :: corr_spec
    INTEGER :: icv, ift, is
    REAL(kind=r8) :: temp_corr(ncv, 0:2, 0:pl%ns-1), corr_fria_d(ncv), &
&   corr_tfia_d(ncv), k2_mean(ncv), k2_tmp(nft, 0:1)
    REAL(kind=r8) :: temp_corrd0(nbdirsmax0, ncv, 0:2, 0:pl%ns-1), &
&   corr_fria_dd0(nbdirsmax0, ncv), corr_tfia_dd0(nbdirsmax0, ncv), &
&   k2_meand0(nbdirsmax0, ncv), k2_tmpd0(nbdirsmax0, nft, 0:1)
    REAL(kind=r8) :: temp_corrd(nbdirsmax, ncv, 0:2, 0:pl%ns-1), &
&   corr_fria_dd(nbdirsmax, ncv), corr_tfia_dd(nbdirsmax, ncv), k2_meand&
&   (nbdirsmax, ncv), k2_tmpd(nbdirsmax, nft, 0:1)
    REAL(kind=r8) :: temp_corrdd(nbdirsmax0, nbdirsmax, ncv, 0:2, 0:pl%&
&   ns-1), corr_fria_ddd(nbdirsmax0, nbdirsmax, ncv), corr_tfia_ddd(&
&   nbdirsmax0, nbdirsmax, ncv), k2_meandd(nbdirsmax0, nbdirsmax, ncv), &
&   k2_tmpdd(nbdirsmax0, nbdirsmax, nft, 0:1)
    INTRINSIC SQRT
    REAL(r8) :: result1
    REAL(kind=r8) :: arg1
    REAL(kind=r8) :: result10
    CHARACTER(len=30) :: arg10
    CHARACTER(len=31) :: arg11
    INTEGER :: nd
    REAL(kind=r8) :: temp
    REAL(kind=r8), DIMENSION(nbdirsmax0) :: tempd
    REAL(r8) :: temp0
    REAL(r8), DIMENSION(nbdirsmax0) :: temp0d
    REAL(kind=r8) :: temp1
    REAL(kind=r8), DIMENSION(nbdirsmax0) :: temp1d
    REAL(kind=r8) :: temp2
    REAL(kind=r8), DIMENSION(nbdirsmax0) :: temp2d
    INTEGER :: nbdirs
    INTEGER :: nd0
    REAL(kind=r8) :: temp3
    REAL(r8) :: temp4
    REAL(r8) :: temp5
    REAL(r8) :: temp6
    REAL(kind=r8) :: temp7
    INTEGER :: nbdirs0
!-----------------------------------------------------------------------
!
    corr_spec = switch%zhdanov_nc_spec - 1
    CALL IPGETI('b2sifrtf_iout', iout)
    CALL B2MOD_FRTF_NCCORR_PREP_DV_DV(ncv, mpg, geo, pl, pld0, pld, pldd&
&                               , co, cod0, cod, codd, rt, rtd0, rtd, &
&                               rtdd, zeff, zeffd0, zeffd, zeffdd, &
&                               nbdirs, nbdirs0)
    corr_fria_d = 0.0_R8
    corr_tfia_d = 0.0_R8
    DO nd=1,nbdirs
      DO nd0=nd,nbdirs0
        corr_friadd(nd0, nd, :, :) = 0.D0
        corr_tfiadd(nd0, nd, :, :) = 0.D0
      END DO
      corr_friad(nd, :, :) = 0.d0
      corr_tfiad(nd, :, :) = 0.d0
    END DO
    DO nd0=1,nbdirs0
      corr_friad0(nd0, :, :) = 0.D0
      corr_tfiad0(nd0, :, :) = 0.D0
    END DO
    corr_fria = 1.0_R8
    corr_tfia = 1.0_R8
    temp_corr = 0.0_R8
    k2_mean = 0.0_R8
    k2_tmp = 0.0_R8
    k2_tmpd = 0.d0
    k2_tmpd0 = 0.D0
    k2_tmpdd = 0.D0
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) THEN
          DO nd=1,nbdirs
            DO nd0=nd,nbdirs0
              k2_tmpdd(nd0, nd, ift, 0) = k2_tmpdd(nd0, nd, ift, 0) + &
&               geo%cvvol(icv)*codd%k2(nd0, nd, icv)
            END DO
            k2_tmpd(nd, ift, 0) = k2_tmpd(nd, ift, 0) + geo%cvvol(icv)*&
&             cod%k2(nd, icv)
          END DO
          DO nd0=1,nbdirs0
            k2_tmpd0(nd0, ift, 0) = k2_tmpd0(nd0, ift, 0) + geo%cvvol(&
&             icv)*cod0%k2(nd0, icv)
          END DO
          k2_tmp(ift, 0) = k2_tmp(ift, 0) + co%k2(icv)*geo%cvvol(icv)
          k2_tmp(ift, 1) = k2_tmp(ift, 1) + geo%cvvol(icv)
        END IF
      END IF
    END DO
    k2_meand = 0.d0
    k2_meandd = 0.D0
    k2_meand0 = 0.D0
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) THEN
          temp3 = k2_tmp(ift, 0)/k2_tmp(ift, 1)
          DO nd0=1,nbdirs0
            tempd(nd0) = (k2_tmpd0(nd0, ift, 0)-temp3*k2_tmpd0(nd0, ift&
&             , 1))/k2_tmp(ift, 1)
          END DO
          temp = temp3
          DO nd=1,nbdirs
            temp3 = (k2_tmpd(nd, ift, 0)-temp*k2_tmpd(nd, ift, 1))/&
&             k2_tmp(ift, 1)
            DO nd0=1,nbdirs0
              k2_meandd(nd0, nd, icv) = (k2_tmpdd(nd0, nd, ift, 0)-&
&               k2_tmpd(nd, ift, 1)*tempd(nd0)-temp*k2_tmpdd(nd0, nd, &
&               ift, 1)-temp3*k2_tmpd0(nd0, ift, 1))/k2_tmp(ift, 1)
            END DO
            k2_meand(nd, icv) = temp3
          END DO
          DO nd0=1,nbdirs0
            k2_meand0(nd0, icv) = tempd(nd0)
          END DO
          k2_mean(icv) = temp
        END IF
      END IF
    END DO
    corr_fria_dd = 0.d0
    temp_corrd = 0.d0
    corr_tfia_dd = 0.d0
    corr_fria_dd0 = 0.D0
    temp_corrdd = 0.D0
    temp_corrd0 = 0.D0
    corr_fria_ddd = 0.D0
    corr_tfia_dd0 = 0.D0
    corr_tfia_ddd = 0.D0
!
    DO icv=1,mpg%nci
! coefficients are calculated only inside the separatrix and for plasma with low main ion collisionality
      IF (mpg%cvonclosedsurface(icv) .AND. g_hs_style(icv) .LE. 5.0_R8) &
&     THEN
!this is a temporary decision
        ift = mpg%cvft(icv)
        DO is=0,pl%ns-1
!                if (switch%Zhdanov_closure.eq.1) then
!
          IF (rt%rza(icv, is) .GE. switch%zhdanov_nc_min .AND. ift .GT. &
&             0) THEN
            temp = g_hs_style(icv)*g_hs_style(icv) + 1.0_R8
            temp4 = (0.44_R8*alpha_hs_style(icv, is)**0.77_R8-0.36_R8*&
&             alpha_hs_style(icv, is)+0.01_R8)/temp
            DO nd0=1,nbdirs0
! coefficients are calculated only for chosen ions of the chosen impurity
              tempd(nd0) = 2*g_hs_style(icv)*g_hs_styled0(nd0, icv)
              temp0d(nd0) = ((0.44_R8*0.77_R8*alpha_hs_style(icv, is)**(&
&               -0.23)-0.36_R8)*alpha_hs_styled0(nd0, icv, is)-temp4*&
&               tempd(nd0))/temp
            END DO
            temp0 = temp4
            DO nd=1,nbdirs
              temp4 = 0.77_R8*0.44_R8*alpha_hs_style(icv, is)**(-0.23) -&
&               0.36_R8
              temp5 = 2*temp0*g_hs_style(icv)
              temp6 = (temp4*alpha_hs_styled(nd, icv, is)-temp5*&
&               g_hs_styled(nd, icv))/temp
              DO nd0=1,nbdirs0
                corr_friadd(nd0, nd, icv, is) = (temp4*alpha_hs_styledd(&
&                 nd0, nd, icv, is)-alpha_hs_styled(nd, icv, is)*0.77_R8&
&                 *0.44_R8*0.23*alpha_hs_style(icv, is)**(-1.23)*&
&                 alpha_hs_styled0(nd0, icv, is)-g_hs_styled(nd, icv)*(&
&                 g_hs_style(icv)*2*temp0d(nd0)+2*temp0*g_hs_styled0(nd0&
&                 , icv))-temp5*g_hs_styledd(nd0, nd, icv)-temp6*tempd(&
&                 nd0))/temp
              END DO
              corr_friad(nd, icv, is) = temp6
            END DO
            corr_fria(icv, is) = temp0 + 1.0_R8
            temp0 = 2.5_R8*crtaancv(icv, s2nucl(pl%ismain)-1, s2nucl(is)&
&             -1)
            temp3 = chtaancv(icv, s2nucl(pl%ismain)-1)/temp0
            DO nd0=1,nbdirs0
              corr_friad0(nd0, icv, is) = temp0d(nd0)
              temp0d(nd0) = 2.5_R8*crtaancvd0(nd0, icv, s2nucl(pl%ismain&
&               )-1, s2nucl(is)-1)
              tempd(nd0) = (chtaancvd0(nd0, icv, s2nucl(pl%ismain)-1)-&
&               temp3*temp0d(nd0))/temp0
            END DO
!
            result1 = SQRT(2.0_R8)
            temp = temp3
            DO nd=1,nbdirs
              temp3 = crtaancvd(nd, icv, s2nucl(pl%ismain)-1, s2nucl(is)&
&               -1)
              temp7 = (chtaancvd(nd, icv, s2nucl(pl%ismain)-1)-2.5_R8*&
&               temp*temp3)/temp0
              DO nd0=1,nbdirs0
                temp_corrdd(nd0, nd, icv, 0, is) = result1*(chtaancvdd(&
&                 nd0, nd, icv, s2nucl(pl%ismain)-1)-2.5_R8*(temp3*tempd&
&                 (nd0)+temp*crtaancvdd(nd0, nd, icv, s2nucl(pl%ismain)-&
&                 1, s2nucl(is)-1))-temp7*temp0d(nd0))/temp0
              END DO
              temp_corrd(nd, icv, 0, is) = result1*temp7
            END DO
            arg1 = geo%fteps(ift)**3
            result10 = SQRT(arg1)
            temp0 = 0.4_R8*alpha_hs_style(icv, is) + 0.36_R8
            temp7 = 2.4_R8*result10/(temp0*(g_hs_style(icv)*g_hs_style(&
&             icv))+1.0_R8)
            DO nd0=1,nbdirs0
              temp_corrd0(nd0, icv, 0, is) = result1*tempd(nd0)
              temp0d(nd0) = 0.4_R8*alpha_hs_styled0(nd0, icv, is)
              tempd(nd0) = -(temp7*(g_hs_style(icv)**2*temp0d(nd0)+temp0&
&               *2*g_hs_style(icv)*g_hs_styled0(nd0, icv))/(temp0*&
&               g_hs_style(icv)**2+1.0_R8))
            END DO
            temp_corr(icv, 0, is) = result1*temp
            temp = temp7
            DO nd=1,nbdirs
              temp7 = g_hs_style(icv)*g_hs_style(icv)
              temp3 = temp/(temp0*temp7+1.0_R8)
              temp6 = 2*temp0*g_hs_style(icv)
              temp5 = 0.4_R8*(g_hs_style(icv)*g_hs_style(icv))*&
&               alpha_hs_styled(nd, icv, is) + temp6*g_hs_styled(nd, icv&
&               )
              DO nd0=1,nbdirs0
                temp_corrdd(nd0, nd, icv, 1, is) = -(temp3*(0.4_R8*(&
&                 alpha_hs_styled(nd, icv, is)*2*g_hs_style(icv)*&
&                 g_hs_styled0(nd0, icv)+g_hs_style(icv)**2*&
&                 alpha_hs_styledd(nd0, nd, icv, is))+g_hs_styled(nd, &
&                 icv)*(g_hs_style(icv)*2*temp0d(nd0)+2*temp0*&
&                 g_hs_styled0(nd0, icv))+temp6*g_hs_styledd(nd0, nd, &
&                 icv))+temp5*(tempd(nd0)-temp3*(temp7*temp0d(nd0)+temp0&
&                 *2*g_hs_style(icv)*g_hs_styled0(nd0, icv)))/(temp0*&
&                 temp7+1.0_R8))
              END DO
              temp_corrd(nd, icv, 1, is) = -(temp5*temp3)
            END DO
            arg1 = geo%fteps(ift)**3
            result10 = SQRT(arg1)
            temp1 = result10*(g_hs_style(icv)*g_hs_style(icv)) + 1.0_R8
            temp7 = g_hs_style(icv)*g_hs_style(icv)/temp1
            DO nd0=1,nbdirs0
              temp_corrd0(nd0, icv, 1, is) = tempd(nd0)
              temp1d(nd0) = result10*2*g_hs_style(icv)*g_hs_styled0(nd0&
&               , icv)
              temp2d(nd0) = (2*g_hs_style(icv)*g_hs_styled0(nd0, icv)-&
&               temp7*temp1d(nd0))/temp1
            END DO
            temp_corr(icv, 1, is) = temp
            temp = 1.6_R8*(geo%fteps(ift)*geo%fteps(ift)*geo%fteps(ift))
            temp2 = temp7
            DO nd=1,nbdirs
              temp7 = g_hs_styled(nd, icv)/temp1
              temp3 = 2*g_hs_style(icv) - 2*result10*temp2*g_hs_style(&
&               icv)
              DO nd0=1,nbdirs0
                temp_corrdd(nd0, nd, icv, 2, is) = temp*(temp7*(2*&
&                 g_hs_styled0(nd0, icv)-result10*2*(g_hs_style(icv)*&
&                 temp2d(nd0)+temp2*g_hs_styled0(nd0, icv)))+temp3*(&
&                 g_hs_styledd(nd0, nd, icv)-temp7*temp1d(nd0))/temp1)
              END DO
              temp_corrd(nd, icv, 2, is) = temp*(temp3*temp7)
            END DO
            temp_corr(icv, 2, is) = temp*temp2
            temp7 = (temp_corr(icv, 0, is)*temp_corr(icv, 1, is)+&
&             temp_corr(icv, 2, is))/k2_mean(icv)
            DO nd0=1,nbdirs0
              temp_corrd0(nd0, icv, 2, is) = temp*temp2d(nd0)
              temp2d(nd0) = (temp_corr(icv, 1, is)*temp_corrd0(nd0, icv&
&               , 0, is)+temp_corr(icv, 0, is)*temp_corrd0(nd0, icv, 1, &
&               is)+temp_corrd0(nd0, icv, 2, is)-temp7*k2_meand0(nd0, &
&               icv))/k2_mean(icv)
            END DO
            temp2 = temp7
            DO nd=1,nbdirs
              temp7 = (temp_corr(icv, 1, is)*temp_corrd(nd, icv, 0, is)+&
&               temp_corr(icv, 0, is)*temp_corrd(nd, icv, 1, is)+&
&               temp_corrd(nd, icv, 2, is)-temp2*k2_meand(nd, icv))/&
&               k2_mean(icv)
              DO nd0=1,nbdirs0
                corr_tfiadd(nd0, nd, icv, is) = (temp_corrd(nd, icv, 0, &
&                 is)*temp_corrd0(nd0, icv, 1, is)+temp_corr(icv, 1, is)&
&                 *temp_corrdd(nd0, nd, icv, 0, is)+temp_corrd(nd, icv, &
&                 1, is)*temp_corrd0(nd0, icv, 0, is)+temp_corr(icv, 0, &
&                 is)*temp_corrdd(nd0, nd, icv, 1, is)+temp_corrdd(nd0, &
&                 nd, icv, 2, is)-k2_meand(nd, icv)*temp2d(nd0)-temp2*&
&                 k2_meandd(nd0, nd, icv)-temp7*k2_meand0(nd0, icv))/&
&                 k2_mean(icv)
              END DO
              corr_tfiad(nd, icv, is) = temp7
            END DO
            DO nd0=1,nbdirs0
              corr_tfiad0(nd0, icv, is) = temp2d(nd0)
            END DO
            corr_tfia(icv, is) = temp2
          END IF
!
! the correction for main ions is calculated to make total forces zero
          IF (s2nucl(is) - 1 .EQ. corr_spec) THEN
            temp2 = z2n_cv(icv, s2nucl(is)-1)
            temp6 = pl%na(icv, is)/temp2
            DO nd0=1,nbdirs0
!
              temp2d(nd0) = z2n_cvd0(nd0, icv, s2nucl(is)-1)
              temp0d(nd0) = (pld0%na(nd0, icv, is)-temp6*temp2d(nd0))/&
&               temp2
              temp1d(nd0) = rt%rz2(icv, is)*corr_friad0(nd0, icv, is) + &
&               corr_fria(icv, is)*rtd0%rz2(nd0, icv, is)
            END DO
            temp0 = temp6
            temp1 = corr_fria(icv, is)*rt%rz2(icv, is)
            DO nd=1,nbdirs
              temp6 = rt%rz2(icv, is)*corr_friad(nd, icv, is) + &
&               corr_fria(icv, is)*rtd%rz2(nd, icv, is)
              temp7 = temp1/temp2
              temp3 = z2n_cvd(nd, icv, s2nucl(is)-1)
              temp5 = pld%na(nd, icv, is) - temp0*temp3
              DO nd0=1,nbdirs0
                corr_fria_ddd(nd0, nd, icv) = corr_fria_ddd(nd0, nd, icv&
&                 ) + temp6*temp0d(nd0) + temp0*(corr_friad(nd, icv, is)&
&                 *rtd0%rz2(nd0, icv, is)+rt%rz2(icv, is)*corr_friadd(&
&                 nd0, nd, icv, is)+rtd%rz2(nd, icv, is)*corr_friad0(nd0&
&                 , icv, is)+corr_fria(icv, is)*rtdd%rz2(nd0, nd, icv, &
&                 is)) + temp7*(pldd%na(nd0, nd, icv, is)-temp3*temp0d(&
&                 nd0)-temp0*z2n_cvdd(nd0, nd, icv, s2nucl(is)-1)) + &
&                 temp5*(temp1d(nd0)-temp7*temp2d(nd0))/temp2
              END DO
              corr_fria_dd(nd, icv) = corr_fria_dd(nd, icv) + temp0*&
&               temp6 + temp5*temp7
            END DO
            temp2 = z2n_cv(icv, s2nucl(is)-1)
            temp6 = pl%na(icv, is)/temp2
            DO nd0=1,nbdirs0
              corr_fria_dd0(nd0, icv) = corr_fria_dd0(nd0, icv) + temp0*&
&               temp1d(nd0) + temp1*temp0d(nd0)
              temp2d(nd0) = z2n_cvd0(nd0, icv, s2nucl(is)-1)
              temp0d(nd0) = (pld0%na(nd0, icv, is)-temp6*temp2d(nd0))/&
&               temp2
              temp1d(nd0) = rt%rz2(icv, is)*corr_tfiad0(nd0, icv, is) + &
&               corr_tfia(icv, is)*rtd0%rz2(nd0, icv, is)
            END DO
            corr_fria_d(icv) = corr_fria_d(icv) + temp1*temp0
            temp0 = temp6
            temp1 = corr_tfia(icv, is)*rt%rz2(icv, is)
            DO nd=1,nbdirs
              temp6 = rt%rz2(icv, is)*corr_tfiad(nd, icv, is) + &
&               corr_tfia(icv, is)*rtd%rz2(nd, icv, is)
              temp7 = temp1/temp2
              temp3 = z2n_cvd(nd, icv, s2nucl(is)-1)
              temp5 = pld%na(nd, icv, is) - temp0*temp3
              DO nd0=1,nbdirs0
                corr_tfia_ddd(nd0, nd, icv) = corr_tfia_ddd(nd0, nd, icv&
&                 ) + temp6*temp0d(nd0) + temp0*(corr_tfiad(nd, icv, is)&
&                 *rtd0%rz2(nd0, icv, is)+rt%rz2(icv, is)*corr_tfiadd(&
&                 nd0, nd, icv, is)+rtd%rz2(nd, icv, is)*corr_tfiad0(nd0&
&                 , icv, is)+corr_tfia(icv, is)*rtdd%rz2(nd0, nd, icv, &
&                 is)) + temp7*(pldd%na(nd0, nd, icv, is)-temp3*temp0d(&
&                 nd0)-temp0*z2n_cvdd(nd0, nd, icv, s2nucl(is)-1)) + &
&                 temp5*(temp1d(nd0)-temp7*temp2d(nd0))/temp2
              END DO
              corr_tfia_dd(nd, icv) = corr_tfia_dd(nd, icv) + temp0*&
&               temp6 + temp5*temp7
            END DO
            DO nd0=1,nbdirs0
              corr_tfia_dd0(nd0, icv) = corr_tfia_dd0(nd0, icv) + temp0*&
&               temp1d(nd0) + temp1*temp0d(nd0)
            END DO
            corr_tfia_d(icv) = corr_tfia_d(icv) + temp1*temp0
          END IF
        END DO
        DO nd=1,nbdirs
          DO nd0=nd,nbdirs0
            corr_friadd(nd0, nd, icv, pl%ismain) = corr_fria_ddd(nd0, nd&
&             , icv)
            corr_tfiadd(nd0, nd, icv, pl%ismain) = corr_tfia_ddd(nd0, nd&
&             , icv)
          END DO
          corr_friad(nd, icv, pl%ismain) = corr_fria_dd(nd, icv)
          corr_tfiad(nd, icv, pl%ismain) = corr_tfia_dd(nd, icv)
        END DO
        DO nd0=1,nbdirs0
          corr_friad0(nd0, icv, pl%ismain) = corr_fria_dd0(nd0, icv)
          corr_tfiad0(nd0, icv, pl%ismain) = corr_tfia_dd0(nd0, icv)
        END DO
        corr_fria(icv, pl%ismain) = corr_fria_d(icv)
        corr_tfia(icv, pl%ismain) = corr_tfia_d(icv)
!
      END IF
    END DO
!
    IF (iout .NE. 0) THEN
!  .or. iout_b2wdat.eq.4) then
      DO is=0,pl%ns-1
        WRITE(chns, '(i3.3)') is
        arg10 = 'b2mod_frtf_nccorr_coefs_temp0_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 0, is), arg10)
        arg10 = 'b2mod_frtf_nccorr_coefs_temp1_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 1, is), arg10)
        arg10 = 'b2mod_frtf_nccorr_coefs_temp2_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 2, is), arg10)
      END DO
      arg11 = 'b2mod_frtf_nccorr_coefs_k2mean_'//chns
      CALL MY_OUT_US(70, ncv, 0, k2_mean, arg11)
    END IF
!
    RETURN
  END SUBROUTINE B2MOD_FRTF_NCCORR_COEFS_DV_DV

!  Differentiation of b2mod_frtf_nccorr_coefs in forward (tangent) mode (with options multiDirectional context noISIZE r8):
!   variations   of useful results: *corr_tfia *g_hs_style *corr_fria
!                *alpha_hs_style
!   with respect to varying inputs: *corr_tfia *g_hs_style *corr_fria
!                *alpha_hs_style chtaancv zeff crtaancv *(rt.rz2)
!                z2n_cv *(co.nu2) *(co.k2) *(pl.na)
!   Plus diff mem management of: corr_tfia:in g_hs_style:in corr_fria:in
!                alpha_hs_style:in geo.cvvol:in geo.fteps:in rt.rza:in
!                rt.rz2:in co.nu2:in co.k2:in pl.na:in
!
  SUBROUTINE B2MOD_FRTF_NCCORR_COEFS_DV(ncv, nft, mpg, mpgd, geo, geod, &
&   pl, pld, co, cod, rt, rtd, switch, chtaancv, chtaancvd, crtaancv, &
&   crtaancvd, z2n_cv, z2n_cvd, zeff, zeffd, nbdirs)
    USE B2US_MAP_DIFFV_DIFFV
    USE B2US_GEO_DIFFV_DIFFV
    USE B2US_PLASMA_DIFFV_DIFFV
    USE B2MOD_SWITCHES_DIFFV_DIFFV
!  Hint: nbdirsmax should be the maximum number of differentiation directions
    USE B2MOD_DIFFSIZES
    IMPLICIT NONE
    INTEGER, INTENT(IN) :: ncv, nft
    TYPE(MAPPING) :: mpg
    TYPE(MAPPING_DIFFV) :: mpgd
    TYPE(GEOMETRY) :: geo
    TYPE(GEOMETRY_DIFFV) :: geod
    TYPE(B2PLASMA) :: pl
    TYPE(B2PLASMA_DIFFV) :: pld
    TYPE(B2COEFF) :: co
    TYPE(B2COEFF_DIFFV) :: cod
    TYPE(B2RATES) :: rt
    TYPE(B2RATES_DIFFV) :: rtd
    TYPE(SWITCHES) :: switch
    REAL(kind=r8) :: zeff(ncv), chtaancv(ncv, 0:nspecies-1), crtaancv(&
&   ncv, 0:nspecies-1, 0:nspecies-1), z2n_cv(ncv, 0:nspecies-1)
    REAL(kind=r8) :: zeffd(nbdirsmax, ncv), chtaancvd(nbdirsmax, ncv, 0:&
&   nspecies-1), crtaancvd(nbdirsmax, ncv, 0:nspecies-1, 0:nspecies-1), &
&   z2n_cvd(nbdirsmax, ncv, 0:nspecies-1)
!-----------------------------------------------------------------------
!.documentation
!
!  1. purpose
!
!     B2MOD_FRTF_NCCORR_COEFS calculates correction coefficients.
!
!  3. description
!
!     This routine computes:
!     - corr_fria: a correction coefficient that is designed
!                  only for friction of chosen medium-to-high
!                  charged impurity with main ions
!     - corr_tfia: a correction coefficient that is designed
!                  only for thermal force of chosen medium-to-high
!                  charged impurity with main ions
!
!-----------------------------------------------------------------------
!  ..local variabless
    CHARACTER :: chns*3
    INTEGER, SAVE :: iout=0
    INTEGER :: corr_spec
    INTEGER :: icv, ift, is
    REAL(kind=r8) :: temp_corr(ncv, 0:2, 0:pl%ns-1), corr_fria_d(ncv), &
&   corr_tfia_d(ncv), k2_mean(ncv), k2_tmp(nft, 0:1)
    REAL(kind=r8) :: temp_corrd(nbdirsmax, ncv, 0:2, 0:pl%ns-1), &
&   corr_fria_dd(nbdirsmax, ncv), corr_tfia_dd(nbdirsmax, ncv), k2_meand&
&   (nbdirsmax, ncv), k2_tmpd(nbdirsmax, nft, 0:1)
    INTRINSIC SQRT
    REAL(r8) :: result1
    REAL(kind=r8) :: arg1
    REAL(kind=r8) :: result10
    CHARACTER(len=30) :: arg10
    CHARACTER(len=31) :: arg11
    INTEGER :: nd
    REAL(kind=r8) :: temp
    REAL(r8) :: temp0
    REAL(kind=r8) :: temp1
    REAL(kind=r8) :: temp2
    INTEGER :: nbdirs
!-----------------------------------------------------------------------
!
    corr_spec = switch%zhdanov_nc_spec - 1
    CALL IPGETI('b2sifrtf_iout', iout)
    CALL B2MOD_FRTF_NCCORR_PREP_DV(ncv, mpg, geo, pl, pld, co, cod, rt, &
&                            rtd, zeff, zeffd, nbdirs)
    corr_fria_d = 0.0_R8
    corr_tfia_d = 0.0_R8
    DO nd=1,nbdirs
      corr_friad(nd, :, :) = 0.d0
      corr_tfiad(nd, :, :) = 0.d0
    END DO
    corr_fria = 1.0_R8
    corr_tfia = 1.0_R8
    temp_corr = 0.0_R8
    k2_mean = 0.0_R8
    k2_tmp = 0.0_R8
    k2_tmpd = 0.d0
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) THEN
          DO nd=1,nbdirs
            k2_tmpd(nd, ift, 0) = k2_tmpd(nd, ift, 0) + geo%cvvol(icv)*&
&             cod%k2(nd, icv)
          END DO
          k2_tmp(ift, 0) = k2_tmp(ift, 0) + co%k2(icv)*geo%cvvol(icv)
          k2_tmp(ift, 1) = k2_tmp(ift, 1) + geo%cvvol(icv)
        END IF
      END IF
    END DO
    k2_meand = 0.d0
    DO icv=1,mpg%nci
      IF (mpg%cvonclosedsurface(icv)) THEN
        ift = mpg%cvft(icv)
        IF (ift .GT. 0) THEN
          temp = k2_tmp(ift, 0)/k2_tmp(ift, 1)
          DO nd=1,nbdirs
            k2_meand(nd, icv) = (k2_tmpd(nd, ift, 0)-temp*k2_tmpd(nd, &
&             ift, 1))/k2_tmp(ift, 1)
          END DO
          k2_mean(icv) = temp
        END IF
      END IF
    END DO
    corr_fria_dd = 0.d0
    temp_corrd = 0.d0
    corr_tfia_dd = 0.d0
!
    DO icv=1,mpg%nci
! coefficients are calculated only inside the separatrix and for plasma with low main ion collisionality
      IF (mpg%cvonclosedsurface(icv) .AND. g_hs_style(icv) .LE. 5.0_R8) &
&     THEN
!this is a temporary decision
        ift = mpg%cvft(icv)
        DO is=0,pl%ns-1
!                if (switch%Zhdanov_closure.eq.1) then
!
          IF (rt%rza(icv, is) .GE. switch%zhdanov_nc_min .AND. ift .GT. &
&             0) THEN
! coefficients are calculated only for chosen ions of the chosen impurity
            temp = g_hs_style(icv)*g_hs_style(icv) + 1.0_R8
            temp0 = (0.44_R8*alpha_hs_style(icv, is)**0.77_R8-0.36_R8*&
&             alpha_hs_style(icv, is)+0.01_R8)/temp
            DO nd=1,nbdirs
              corr_friad(nd, icv, is) = ((0.44_R8*0.77_R8*alpha_hs_style&
&               (icv, is)**(-0.23)-0.36_R8)*alpha_hs_styled(nd, icv, is)&
&               -temp0*2*g_hs_style(icv)*g_hs_styled(nd, icv))/temp
            END DO
            corr_fria(icv, is) = temp0 + 1.0_R8
!
            result1 = SQRT(2.0_R8)
            temp0 = 2.5_R8*crtaancv(icv, s2nucl(pl%ismain)-1, s2nucl(is)&
&             -1)
            temp = chtaancv(icv, s2nucl(pl%ismain)-1)/temp0
            DO nd=1,nbdirs
              temp_corrd(nd, icv, 0, is) = result1*(chtaancvd(nd, icv, &
&               s2nucl(pl%ismain)-1)-temp*2.5_R8*crtaancvd(nd, icv, &
&               s2nucl(pl%ismain)-1, s2nucl(is)-1))/temp0
            END DO
            temp_corr(icv, 0, is) = result1*temp
            arg1 = geo%fteps(ift)**3
            result10 = SQRT(arg1)
            temp0 = 0.4_R8*alpha_hs_style(icv, is) + 0.36_R8
            temp = 2.4_R8*result10/(temp0*(g_hs_style(icv)*g_hs_style(&
&             icv))+1.0_R8)
            DO nd=1,nbdirs
              temp_corrd(nd, icv, 1, is) = -(temp*(g_hs_style(icv)**2*&
&               0.4_R8*alpha_hs_styled(nd, icv, is)+temp0*2*g_hs_style(&
&               icv)*g_hs_styled(nd, icv))/(temp0*g_hs_style(icv)**2+&
&               1.0_R8))
            END DO
            temp_corr(icv, 1, is) = temp
            arg1 = geo%fteps(ift)**3
            result10 = SQRT(arg1)
            temp = 1.6_R8*(geo%fteps(ift)*geo%fteps(ift)*geo%fteps(ift))
            temp1 = result10*(g_hs_style(icv)*g_hs_style(icv)) + 1.0_R8
            temp2 = g_hs_style(icv)*g_hs_style(icv)/temp1
            DO nd=1,nbdirs
              temp_corrd(nd, icv, 2, is) = temp*(2*g_hs_style(icv)-temp2&
&               *result10*2*g_hs_style(icv))*g_hs_styled(nd, icv)/temp1
            END DO
            temp_corr(icv, 2, is) = temp*temp2
            temp2 = (temp_corr(icv, 0, is)*temp_corr(icv, 1, is)+&
&             temp_corr(icv, 2, is))/k2_mean(icv)
            DO nd=1,nbdirs
              corr_tfiad(nd, icv, is) = (temp_corr(icv, 1, is)*&
&               temp_corrd(nd, icv, 0, is)+temp_corr(icv, 0, is)*&
&               temp_corrd(nd, icv, 1, is)+temp_corrd(nd, icv, 2, is)-&
&               temp2*k2_meand(nd, icv))/k2_mean(icv)
            END DO
            corr_tfia(icv, is) = temp2
          END IF
!
! the correction for main ions is calculated to make total forces zero
          IF (s2nucl(is) - 1 .EQ. corr_spec) THEN
!
            temp2 = z2n_cv(icv, s2nucl(is)-1)
            temp0 = pl%na(icv, is)/temp2
            temp1 = corr_fria(icv, is)*rt%rz2(icv, is)
            DO nd=1,nbdirs
              corr_fria_dd(nd, icv) = corr_fria_dd(nd, icv) + temp0*(rt%&
&               rz2(icv, is)*corr_friad(nd, icv, is)+corr_fria(icv, is)*&
&               rtd%rz2(nd, icv, is)) + temp1*(pld%na(nd, icv, is)-temp0&
&               *z2n_cvd(nd, icv, s2nucl(is)-1))/temp2
            END DO
            corr_fria_d(icv) = corr_fria_d(icv) + temp1*temp0
            temp2 = z2n_cv(icv, s2nucl(is)-1)
            temp0 = pl%na(icv, is)/temp2
            temp1 = corr_tfia(icv, is)*rt%rz2(icv, is)
            DO nd=1,nbdirs
              corr_tfia_dd(nd, icv) = corr_tfia_dd(nd, icv) + temp0*(rt%&
&               rz2(icv, is)*corr_tfiad(nd, icv, is)+corr_tfia(icv, is)*&
&               rtd%rz2(nd, icv, is)) + temp1*(pld%na(nd, icv, is)-temp0&
&               *z2n_cvd(nd, icv, s2nucl(is)-1))/temp2
            END DO
            corr_tfia_d(icv) = corr_tfia_d(icv) + temp1*temp0
          END IF
        END DO
        DO nd=1,nbdirs
          corr_friad(nd, icv, pl%ismain) = corr_fria_dd(nd, icv)
          corr_tfiad(nd, icv, pl%ismain) = corr_tfia_dd(nd, icv)
        END DO
        corr_fria(icv, pl%ismain) = corr_fria_d(icv)
        corr_tfia(icv, pl%ismain) = corr_tfia_d(icv)
!
      END IF
    END DO
!
    IF (iout .NE. 0) THEN
!  .or. iout_b2wdat.eq.4) then
      DO is=0,pl%ns-1
        WRITE(chns, '(i3.3)') is
        arg10 = 'b2mod_frtf_nccorr_coefs_temp0_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 0, is), arg10)
        arg10 = 'b2mod_frtf_nccorr_coefs_temp1_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 1, is), arg10)
        arg10 = 'b2mod_frtf_nccorr_coefs_temp2_'//chns
        CALL MY_OUT_US(70, ncv, 0, temp_corr(:, 2, is), arg10)
      END DO
      arg11 = 'b2mod_frtf_nccorr_coefs_k2mean_'//chns
      CALL MY_OUT_US(70, ncv, 0, k2_mean, arg11)
    END IF
!
    RETURN
  END SUBROUTINE B2MOD_FRTF_NCCORR_COEFS_DV

