  REAL(kind=r8) :: result1
  LOGICAL :: result10
!
!**
!     This routine finds all the cv intersecting with the segment specified in segm
!     It is assumed that segm(1,:) contains x-coordinate and segm(2,:) the y-coordinates
!     list will contain all the CVs intersecting (without repetitions) and nncv the number of
!     CVs. The CVs will be sorted according to mode, mode=1 sorted along x-dir, mode=2 sorted along y-dir
!**
!
  CALL XERTST(mode .GE. 1 .AND. mode .LE. 2, 'mode value not encoded')
!number of CVs in the list
  nncv = 1
  list = 0
  ifail = .false.
  p1 = segm(:, 1)
  q1 = segm(:, 2)
  DO ifc=1,m%nfc
    p2(1) = geo%vxx(m%fcvx(ifc, 1))
    p2(2) = geo%vxy(m%fcvx(ifc, 1))
    q2(1) = geo%vxx(m%fcvx(ifc, 2))
    q2(2) = geo%vxy(m%fcvx(ifc, 2))
!! for artificial slab cases it sometimes happens that vxY and vxX are wrong at the cuts, leading to incorrect intersections.
!! fcHt will be correct though. Therefore we check here if the distance between the vertex points corresponds to the face length.
! If not, no intersection is counted.
    slab_test = .true.
    arg1 = (p2(1)-q2(1))**2 + (p2(2)-q2(2))**2
    result1 = SQRT(arg1)
    IF (result1 .GT. geo%fcht(ifc)*1.1_R8) slab_test = .false.
    result10 = INTERSECTS(p1, q1, p2, q2)
    IF (result10 .AND. slab_test) THEN
      DO ii=1,2
        ic = m%fccv(ifc, ii)
        found = .false.
        kk = 1
        DO WHILE (.NOT.found .AND. kk .LE. nncv)
          IF (ic .NE. 0 .AND. list(kk) .EQ. ic) found = .true.
          kk = kk + 1
        END DO
        IF (.NOT.found) THEN
          IF (nncv .GT. nmax) THEN
            ifail = .true.
            RETURN
          ELSE
            list(nncv) = ic
            nncv = nncv + 1
          END IF
        END IF
      END DO
    END IF
  END DO
  nncv = nncv - 1
!     Now sort the obtained list along the segment: the sort key of a cell is
!     the position of its chord midpoint on the segment (cv_segment_positions).
  IF (nncv .GT. 1) THEN
    ALLOCATE(pos(nncv))
    CALL CV_SEGMENT_POSITIONS_NODIFF(geo, m, segm, list, nncv, pos)
    sgn = 1.0_R8
    IF (segm(mode, 2) .LT. segm(mode, 1)) sgn = -1.0_R8
    DO ii=2,nncv
      ic = list(ii)
      key = sgn*pos(ii)
      DO kk=ii-1,1,-1
        IF (sgn*pos(kk) .LE. key) THEN
          GOTO 100
        ELSE
          list(kk+1) = list(kk)
          pos(kk+1) = pos(kk)
        END IF
      END DO
 100  list(kk+1) = ic
      pos(kk+1) = key*sgn
    END DO
    DEALLOCATE(pos)
  END IF
!
  RETURN
END SUBROUTINE CV_INTERSECTIONS_NODIFF

