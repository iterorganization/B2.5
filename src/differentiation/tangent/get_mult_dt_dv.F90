    CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%uadia(:, &
&                  1, :), uadia_c1)
    CALL INTCELL_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%vedia(:, 0), &
&                 vedia_c0)
    CALL INTCELL_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%vedia(:, 1), &
&                 vedia_c1)
    CALL INTCELL_NODIFF(nfc, ncv, mpg, mpg%intcellp, dv%veecrb(:, 0), &
&                 veecrb_c0)
    CALL INTCELL_NODIFF(nfc, ncv, mpg, mpg%intcellr, dv%veecrb(:, 1), &
&                 veecrb_c1)
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      wrk00 = uadia_c0(icv, :) + geo%cvbb(icv, 0)/geo%cvbb(icv, 3)*ua(&
&       icv, :)
      wrk11 = uadia_c1(icv, :)
      WHERE (wrk00 .GE. 0.) 
        dabs0 = wrk00
      ELSEWHERE
        dabs0 = -wrk00
      END WHERE
      vx_a = MAXVAL(dabs0)
      x1 = vedia_c0(icv) + veecrb_c0(icv) + geo%cvbb(icv, 0)/geo%cvbb(&
&       icv, 3)*dv%ue(icv)
      IF (x1 .GE. 0.) THEN
        vx_e = x1
      ELSE
        vx_e = -x1
      END IF
      WHERE (wrk11 .GE. 0.) 
        dabs1 = wrk11
      ELSEWHERE
        dabs1 = -wrk11
      END WHERE
      vy_a = MAXVAL(dabs1)
      IF (vedia_c1(icv) + veecrb_c1(icv) .GE. 0.) THEN
        vy_e = vedia_c1(icv) + veecrb_c1(icv)
      ELSE
        vy_e = -(vedia_c1(icv)+veecrb_c1(icv))
      END IF
      IF (vx_a .LT. vx_e) THEN
        max1 = vx_e
      ELSE
        max1 = vx_a
      END IF
      dtx = cmax*hx/max1
      IF (vy_a .LT. vy_e) THEN
        max2 = vy_e
      ELSE
        max2 = vy_a
      END IF
      dty = cmax*hy/max2
      IF (dtx .GT. dty) THEN
        dt3 = dty
      ELSE
        dt3 = dtx
      END IF
      IF (dtim .LT. dt3) THEN
        x2 = dt3
      ELSE
        x2 = dtim
      END IF
      IF (x2 .GT. dtim*mult_max) THEN
        dt3 = dtim*mult_max
      ELSE
        dt3 = x2
      END IF
      mult_dt(icv) = dt3/dtim
    END DO
    DO ifilter=1,nfilter
      mult_dt_tmp = mult_dt
      DO ifc=1,nfc
        i1 = mpg%fccv(ifc, 1)
        i2 = mpg%fccv(ifc, 2)
        IF (mult_dt_tmp(i1) .GT. mult_dt_tmp(i2)) THEN
          min_mult = mult_dt_tmp(i2)
        ELSE
          min_mult = mult_dt_tmp(i1)
        END IF
        mult_dt(i1) = min_mult
        mult_dt(i2) = min_mult
      END DO
    END DO
  ELSE IF (style .EQ. 4) THEN
!c Highly experimental work! Use with care.
!! For this option mult_dt is not used but other pre-compuations are performed here
!! interpolate drift velocities to cell centers
    mult_dt = 1.0_R8
    arg1 = ns - 1
    CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellp, dv%uadia(:, &
&                  0, :), wrk0)
    arg1 = ns - 1
    CALL INTCELL1_NODIFF(nfc, ncv, arg1, mpg, mpg%intcellr, dv%uadia(:, &
&                  1, :), wrk1)
    DO icv=1,ncv
!! hx and hy are approximations for non-quadrilateral cells
      hy = geo%cvvol(icv)/geo%cvhx(icv)/geo%cvhz(icv)
      hx = geo%cvhz(icv)
      wrk00 = wrk0(icv, :)
      wrk11 = wrk1(icv, :)
      DO is=0,ns-1
        IF (wrk00(is) .GE. 0.) THEN
          vx = wrk00(is)
        ELSE
          vx = -wrk00(is)
        END IF
        IF (wrk11(is) .GE. 0.) THEN
          vy = wrk11(is)
        ELSE
          vy = -wrk11(is)
        END IF
        dtx = cmax*hx/(vx+0.001_R8)
        dty = cmax*hy/(vy+0.001_R8)
        IF (dtx .GT. dty) THEN
          dt4 = dty
        ELSE
          dt4 = dtx
        END IF
        dt_var4_ns(icv, is) = dt4
      END DO
      dt_var4_min(icv) = MINVAL(dt_var4_ns(icv, :))
    END DO
  ELSE
!
    CALL XERRAB('This b2mndt_var_style is not available')
  END IF
!
!   ..return
  RETURN
!
!-----------------------------------------------------------------------
!
!
END SUBROUTINE GET_MULT_DT_NODIFF

